class SchemaViolationError(ValueError):
    """An LLM reply whose present fields violate their declared schema types."""


def _type_issue(ftype, val):
    """Why `val` violates `ftype`, or None. Unknown/union types are not checked."""
    if ftype in ("string", "datetime"):
        ok = isinstance(val, str)
    elif ftype in ("integer", "float", "number"):
        ok = isinstance(val, (int, float)) and not isinstance(val, bool)
    elif ftype == "boolean":
        ok = isinstance(val, bool)
    elif ftype.startswith("list") or ftype == "array":
        ok = isinstance(val, list)
    elif ftype.startswith("enum["):
        allowed = [v.strip() for v in ftype[5:-1].split(",")]
        return None if val in allowed else f"value {val!r} not in {allowed}"
    elif ftype == "object" or ftype in SCHEMAS:
        ok = isinstance(val, dict)
    else:
        return None
    return None if ok else f"expected {ftype}, got {type(val).__name__}"


def validate_output(data, schema_name):
    """Count schema issues in a parsed LLM reply (missing fields included). Returns list of issues."""
    schema = SCHEMAS.get(schema_name)
    if not schema or "raw" in data:
        return []
    issues = []
    for field in schema["fields"]:
        fname = field["name"]
        ftype = field["type"]
        if fname not in data:
            if not field.get("optional", False):
                issues.append(f"Missing field '{fname}' ({ftype})")
            continue
        problem = _type_issue(ftype, data[fname])
        if problem:
            issues.append(f"Field '{fname}' {problem}")
    if issues:
        print(f"    [SCHEMA] {schema_name}: {len(issues)} issue(s): {issues[0]}")
    return issues


def require_valid_output(data, schema_name, source):
    """Return the reply with nulls dropped, or raise SchemaViolationError.

    A present field of the wrong type is refused before anything is merged or
    routed: {"answer": 42} used to be merged and crash emit_answer, and an
    out-of-enum `type` was routed as though it were valid. An omitted field or a
    null is not a violation -- it means "not provided" and the caller resets it
    to its default. A reply that is not a JSON object at all is a violation
    too (it used to become an empty step and a "No answer found" run), except
    for a single-string-field schema, where the reply text is that field.
    """
    schema = SCHEMAS.get(schema_name)
    if not schema:
        return data
    fields = schema["fields"]
    names = {f["name"] for f in fields}
    # parse_response marks a reply that is not a JSON object as {"raw": text}
    # (not JSON at all) or {"value": x} (JSON, but not an object).
    raw = data.get("raw") if set(data) == {"raw"} and isinstance(data.get("raw"), str) else None
    bare = set(data) == {"value"} and "value" not in names
    if raw is not None or bare:
        # A schema whose only field is a string has one unambiguous free-text
        # reading: the whole reply is that field.
        if len(fields) == 1 and fields[0]["type"] == "string" and raw is not None and raw.strip():
            return {fields[0]["name"]: raw.strip()}
        shown = raw if raw is not None else json.dumps(data["value"], default=str)
        print(f"    [SCHEMA] {source} did not return a {schema_name} JSON object: {shown[:200]!r}")
        raise SchemaViolationError(f"{source} did not return a {schema_name} JSON object: {shown[:200]!r}")
    cleaned = {k: v for k, v in data.items() if v is not None}
    # An object carrying none of the declared fields is not a reply in this
    # schema: resetting every field to its default let the step carry on as if
    # the model had answered. Only when the schema requires something -- a reply
    # holding just an optional declared field (e.g. tool_calls) still counts.
    if any(not f.get("optional") for f in fields) and not (names & set(cleaned)):
        shown = json.dumps(data, default=str)
        print(f"    [SCHEMA] {source} returned no {schema_name} field ({sorted(names)}): {shown[:200]!r}")
        raise SchemaViolationError(f"{source} returned no {schema_name} field ({sorted(names)}): {shown[:200]!r}")
    errors = []
    for field in schema["fields"]:
        if field["name"] in cleaned:
            problem = _type_issue(field["type"], cleaned[field["name"]])
            if problem:
                errors.append(f"{field['name']}: {problem}")
    if errors:
        print(f"    [SCHEMA] {source} returned an invalid {schema_name}: {'; '.join(errors)}")
        raise SchemaViolationError(f"{source} returned an invalid {schema_name}: {'; '.join(errors)}")
    return cleaned



def build_input(state, schema_name):
    """Build an input dict for an agent call using schema field names.
    Pulls matching keys from state.data, checking both flat keys and
    values nested inside dict entries (e.g. state.data["xxx_input"]["field"])."""
    schema = SCHEMAS.get(schema_name)
    if not schema:
        return state.data
    result = {}
    for field in schema["fields"]:
        fname = field["name"]
        if fname in state.data:
            result[fname] = state.data[fname]
        else:
            # Search nested dicts in state.data for the field
            for _k, _v in state.data.items():
                if isinstance(_v, dict) and fname in _v:
                    result[fname] = _v[fname]
                    break
    return result


def output_instruction(schema_name):
    """Generate a JSON output instruction string for the LLM."""
    schema = SCHEMAS.get(schema_name)
    if not schema:
        return ""
    fields = ", ".join(f'"{f["name"]}": <{f["type"]}>' for f in schema["fields"])
    return f"\n\nRespond with ONLY valid JSON matching this schema: {{{fields}}}"


def parse_response(response, schema_name):
    """Parse an LLM response according to an output schema.
    Returns a dict of field values, or {"raw": response} if parsing fails."""
    import re as _re
    text = response.strip()
    # Handle markdown code blocks
    if text.startswith("```"):
        lines = text.split("\n")
        lines = lines[1:]  # skip ```json
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        text = "\n".join(lines)
    # Attempt 1: direct parse
    try:
        parsed = json.loads(text)
        if isinstance(parsed, dict):
            return parsed
        return {"value": parsed}
    except json.JSONDecodeError:
        pass
    # Attempt 2: extract JSON object from prose
    start = text.find("{")
    end = text.rfind("}") + 1
    if start >= 0 and end > start:
        candidate = text[start:end]
        try:
            return json.loads(candidate)
        except json.JSONDecodeError:
            pass
        # Attempt 3: fix trailing commas
        fixed = _re.sub(r",\s*}", "}", candidate)
        fixed = _re.sub(r",\s*]", "]", fixed)
        try:
            return json.loads(fixed)
        except json.JSONDecodeError:
            pass
        # Attempt 4: find matching braces (handle nested)
        depth = 0
        for i, ch in enumerate(text[start:], start):
            if ch == "{": depth += 1
            elif ch == "}": depth -= 1
            if depth == 0:
                try:
                    return json.loads(text[start:i+1])
                except json.JSONDecodeError:
                    break
    return {"raw": response}


