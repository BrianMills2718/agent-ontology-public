def process_run_tools(state):
    """
    Run Tool Calls
    Execute shell/MCP/web operations; use parallel tool for independent reads
    """
    print(f"  → Run Tool Calls")

    # Tool dispatch (single call or tool_calls batch)
    _batch_results = []
    _calls = state.data.get("tool_calls")
    if isinstance(_calls, list) and _calls:
        _dispatch_items = _calls
    else:
        _dispatch_items = [{
            "tool_name": state.data.get("tool_name", ""),
            "arguments": state.data.get("tool_input", state.data.get("action", "")),
        }]
    for _call in _dispatch_items:
        if not isinstance(_call, dict):
            _call = {"tool_name": "", "arguments": _call}
        _tool_name = str(_call.get("tool_name") or _call.get("name") or _call.get("tool") or _call.get("recipient_name") or "").lower().strip()
        if _tool_name.startswith("functions."):
            _tool_name = _tool_name.split(".", 1)[1]
        _tool_input = _call.get("arguments", _call.get("args", _call.get("parameters", _call.get("input", ""))))
        if isinstance(_tool_input, (dict, list)):
            _tool_input = json.dumps(_tool_input, ensure_ascii=False)
        else:
            _tool_input = str(_tool_input)
        if _tool_name in {'multi_tool_use.parallel', 'parallel_tool', 'parallel_tool_tool', 'tool_parallel_tool'}:
            _tool_result = tool_parallel_tool(_tool_input)
            _tool_impl = "parallel_tool"
        elif _tool_name in {'exec_command', 'exec_command_tool', 'exec_command_tool_tool', 'tool_exec_command_tool'}:
            _tool_result = tool_exec_command_tool(_tool_input)
            _tool_impl = "exec_command_tool"
        elif _tool_name in {'tool_write_stdin_tool', 'write_stdin', 'write_stdin_tool', 'write_stdin_tool_tool'}:
            _tool_result = tool_write_stdin_tool(_tool_input)
            _tool_impl = "write_stdin_tool"
        elif _tool_name in {'filesystem', 'filesystem mcp', 'filesystem_mcp', 'filesystem_tool', 'filesystem_tool_tool', 'tool_filesystem_tool'}:
            _tool_result = tool_filesystem_tool(_tool_input)
            _tool_impl = "filesystem_tool"
        elif _tool_name in {'tool_web_tool', 'web search/fetch', 'web_search/fetch', 'web_tool', 'web_tool_tool'}:
            _tool_result = tool_web_tool(_tool_input)
            _tool_impl = "web_tool"
        elif _tool_name in {'apply_patch', 'apply_patch_tool', 'apply_patch_tool_tool', 'tool_apply_patch_tool'}:
            _tool_result = tool_apply_patch_tool(_tool_input)
            _tool_impl = "apply_patch_tool"
        else:
            _tool_result = _runtime_tool_dispatch(_tool_name, _tool_input)
            if isinstance(_tool_result, str) and _tool_result.startswith("[tool ") and "not implemented" in _tool_result:
                _tool_result = f"Unknown tool: {_tool_name}. Available: multi_tool_use.parallel, exec_command, write_stdin, filesystem mcp, web search/fetch, apply_patch"
