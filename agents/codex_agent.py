def process_decide_next_action(state):
    """
    Decide Next Action
    Produce either tool calls or a direct response strategy
    """
    print(f"  → Decide Next Action")

    # Invoke: Reason over context and pick next action
    codex_input = build_input(state, "AgentInput")
    codex_msg = json.dumps(codex_input, default=str)
    codex_raw = invoke_codex(codex_msg, output_schema="ActionDecision")
    codex_result = parse_response(codex_raw, "ActionDecision")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    codex_result = require_valid_output(codex_result, "ActionDecision", 'Codex (GPT-5)')
    state.schema_violations += len(validate_output(codex_result, "ActionDecision"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    state.data["action_type"] = ""
    state.data["tool_calls"] = []
    state.data["draft_response"] = ""
    state.data["done"] = False
    state.data["observation"] = ""
    state.data["tool_results"] = []
    state.data.update(codex_result)
    state.data["action_decision"] = codex_result
    state.data["decide_next_action_result"] = codex_result
    print(f"    ← Codex (GPT-5): {codex_result}")

    return state


