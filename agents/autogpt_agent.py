def process_verify_progress(state):
    """
    Verify Progress
    Check latest action result against success + constraints; may request retry of current step
    """
    print(f"  → Verify Progress")

    # Logic from spec
    import datetime
    constraints = state.data.get("constraints", [])
    if not isinstance(constraints, list):
        constraints = []
    action_result = str(state.data.get("action_result", "") or "")
    success = bool(state.data.get("success", False))
    lc_result = action_result.lower()
    
    matched_constraints = 0
    for raw in constraints:
        text = str(raw or "").strip().lower()
        if not text:
            continue
        tokens = [tok for tok in text.split() if len(tok) >= 3]
        if not tokens:
            continue
        if all(tok in lc_result for tok in tokens[:6]):
            matched_constraints += 1
    
    constraint_count = len([c for c in constraints if str(c or "").strip()])
    constraints_ok = True
    if constraint_count > 0:
        constraints_ok = matched_constraints >= constraint_count
    verification_passed = success and constraints_ok
    
    state.data["verification_checked_at"] = datetime.datetime.now().isoformat()
    state.data["verification_constraint_count"] = constraint_count
    state.data["verification_matched_constraints"] = matched_constraints
    state.data["verification_passed"] = verification_passed
    
    if verification_passed:
        state.data["verification_status"] = "pass"
        state.data["verification_notes"] = "Latest action passed execution and constraint checks."
        state.data["verify_retry_count"] = 0
    else:
        fail_count = int(state.data.get("verification_fail_count", 0) or 0) + 1
        state.data["verification_fail_count"] = fail_count
        retry_count = int(state.data.get("verify_retry_count", 0) or 0)
        max_retries = int(state.data.get("max_verify_retries", 2) or 2)
        if retry_count < max_retries:
            state.data["verification_status"] = "retry"
            state.data["verification_notes"] = "Verification failed; retrying current step."
            state.data["verify_retry_count"] = retry_count + 1
            current_idx = int(state.data.get("current_step_idx", 0) or 0)
            state.data["current_step_idx"] = max(0, current_idx - 1)
            state.data["feedback"] = f"Verification retry requested ({state.data['verify_retry_count']}/{max_retries})."
        else:
            state.data["verification_status"] = "failed_exhausted"
            state.data["verification_notes"] = "Verification failed and retry budget exhausted; continuing."
            state.data["feedback"] = "Verification failed but retry budget exhausted."
    if state.data.get("_done"):
        return state

    return state


