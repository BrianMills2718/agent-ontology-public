def process_execute_external_call(state):
    """
    Execute External Call
    Dispatch typed external interface request through adapter
    """
    print(f"  → Execute External Call")

    # Logic from spec
    import json
    
    cap = str(state.data.get("capability_profile", "restricted") or "restricted").strip().lower()
    if cap in {"external", "unshackled", "full"}:
        cap = "external_enabled"
    if cap not in {"restricted", "external_enabled"}:
        cap = "restricted"
    state.data["capability_profile"] = cap
    
    action_type = str(state.data.get("action_type", "command") or "command").strip().lower()
    if action_type in {"external", "externalcall"}:
        action_type = "external_call"
    state.data["action_type"] = action_type
    
    iface = str(state.data.get("interface_name", "") or "").strip()
    payload = state.data.get("payload", {})
    if not isinstance(payload, dict):
        payload = {"value": payload}
    state.data["payload"] = payload
    state.data["executed_interface"] = iface
    _telemetry = state.data.get("routing_telemetry", {})
    if not isinstance(_telemetry, dict):
        _telemetry = {}
    _telemetry.setdefault("semantic_fallback_dispatches", 0)
    state.data["routing_telemetry"] = _telemetry
    
    if action_type != "external_call":
        if not state.data.get("action_result"):
            state.data["action_result"] = "No external call requested."
        state.data["success"] = bool(state.data.get("success", False))
    elif not iface:
        state.data["action_result"] = "Missing interface_name for external_call."
        state.data["success"] = False
    elif cap != "external_enabled":
        state.data["action_result"] = f"Blocked by capability profile ({cap}): external_call {iface}"
        state.data["success"] = False
    else:
        _ext = _external_tool_dispatch(iface, payload)
        if not isinstance(_ext, dict):
            _ext = {"handled": False, "ok": False, "error": f"Invalid external adapter response: {type(_ext).__name__}"}
        _fallback_used = False
        _handled = bool(_ext.get("handled", False))
        _ok_pre = bool(_ext.get("ok", False))
        _err_pre = str(_ext.get("error", "") or "").strip().lower()
        _needs_semantic_fallback = (not _handled) or ((not _ok_pre) and ("did not handle interface" in _err_pre))
        if _needs_semantic_fallback and iface and iface != "semantic_search":
            _fallback_query = str(
                payload.get("query")
                or state.data.get("proposed_action")
                or state.data.get("current_step")
                or state.data.get("objective")
                or ""
            ).strip()
            _fallback_payload = {"query": _fallback_query}
            _fallback = _external_tool_dispatch("semantic_search", _fallback_payload)
            if not isinstance(_fallback, dict):
                _fallback = {
                    "handled": False,
                    "ok": False,
                    "error": f"Invalid external adapter response: {type(_fallback).__name__}",
                }
            state.data["semantic_fallback_dispatch"] = {
                "from_interface": iface,
                "to_interface": "semantic_search",
                "query": _fallback_query,
                "trigger": "unhandled_external_interface",
                "initial_result": _ext,
                "fallback_result": _fallback,
            }
            _telemetry["semantic_fallback_dispatches"] = int(_telemetry.get("semantic_fallback_dispatches", 0) or 0) + 1
            state.data["semantic_fallback_count"] = int(state.data.get("semantic_fallback_count", 0) or 0) + 1
            _fallback_events = state.data.get("semantic_fallback_events", [])
            if not isinstance(_fallback_events, list):
                _fallback_events = []
            _fallback_events.append(
                {
                    "from_interface": iface,
                    "to_interface": "semantic_search",
                    "query": _fallback_query,
                    "reason": "unhandled_external_interface",
                }
            )
            state.data["semantic_fallback_events"] = _fallback_events[-20:]
            if bool(_fallback.get("handled", False)):
                _ext = _fallback
                iface = "semantic_search"
                state.data["executed_interface"] = iface
                state.data["interface_name"] = iface
                _fallback_used = True
        state.data["external_result"] = _ext
        _ok = bool(_ext.get("ok", False))
        _txt = str(_ext.get("text", "") or "").strip()
        _err = str(_ext.get("error", "") or "").strip()
        _provider = str(_ext.get("provider", "") or "").strip()
        _mode = str(_ext.get("mode", "") or "").strip()
        if _txt:
            _summary = _txt
        elif _err:
            _summary = f"External call error: {_err}"
        else:
            try:
                _summary = json.dumps(_ext, default=str, ensure_ascii=False)
            except Exception:
                _summary = str(_ext)
        if _provider or _mode:
            _summary = f"[{_provider or 'external'} mode={_mode or 'unknown'}] {_summary}"
        if _fallback_used:
            _summary = f"[semantic_fallback {state.data.get('semantic_fallback_dispatch', {}).get('from_interface', '')}->semantic_search] {_summary}"
        state.data["action_result"] = _summary
        state.data["success"] = _ok
    
    step_idx = state.data.get("current_step_idx", 0)
    state.data["key"] = f"step_{step_idx}"
    state.data["value"] = state.data.get("action_result", "")
    if state.data.get("_done"):
        return state

    return state


def process_execute_command(state):
    """
    Execute Command
    Run executor-generated shell command in workspace and capture output
    """
    print(f"  → Execute Command")

    # Logic from spec
    import os
    import subprocess
    
    workspace_dir = state.data.get("workspace_dir") or os.getcwd()
    os.makedirs(workspace_dir, exist_ok=True)
    timeout_seconds = int(os.environ.get("AGENT_ONTOLOGY_COMMAND_TIMEOUT", "30") or "30")
    
    cmd = str(state.data.get("command", "") or "").strip()
    if cmd.upper() in {"NONE", "N/A", "SKIP"}:
        cmd = ""
    action_type = str(state.data.get("action_type", "command") or "command").strip().lower()
    if action_type in {"external", "externalcall"}:
        action_type = "external_call"
    state.data["action_type"] = action_type
    cmd_lower = cmd.lower()
    state.data["executed_command"] = cmd
    cap = str(state.data.get("capability_profile", "restricted") or "restricted").strip().lower()
    if cap in {"external", "unshackled", "full"}:
        cap = "external_enabled"
    if cap not in {"restricted", "external_enabled"}:
        cap = "restricted"
    state.data["capability_profile"] = cap
    
    # If the executor returned no command for a build/coding objective,
    # emit a safe scaffold command so runs still generate concrete files.
    _intent_text = " ".join(
        [
            str(state.data.get("objective", "") or ""),
            str(state.data.get("current_step", "") or ""),
            str(state.data.get("proposed_action", "") or ""),
        ]
    ).lower()
    _build_markers = [
        "build",
        "implement",
        "create",
        "write code",
        "todo",
        "api",
        "app",
        "project",
        "service",
    ]
    _build_intent = any(m in _intent_text for m in _build_markers)
    
    def _apply_autofallback(reason):
        nonlocal cmd, cmd_lower
        cmd = "\n".join(
            [
                "mkdir -p src tests",
                "cat > README.md <<'EOF'",
                "# AutoGPT Workspace Bootstrap",
                "",
                "This workspace was initialized automatically because command execution could not continue safely.",
                f"Reason: {str(reason or '').replace(chr(10), ' ')}",
                "EOF",
                "cat > src/main.py <<'EOF'",
                "def main():",
                "    return 'todo app bootstrap'",
                "",
                "if __name__ == '__main__':",
                "    print(main())",
                "EOF",
                "cat > tests/test_smoke.py <<'EOF'",
                "from src.main import main",
                "",
                "def test_smoke():",
                "    assert main() == 'todo app bootstrap'",
                "EOF",
            ]
        )
        cmd_lower = cmd.lower()
        state.data["command"] = cmd
        state.data["executed_command"] = cmd
        state.data["autofallback_generated_command"] = True
        state.data["autofallback_reason"] = reason
        print(f"    Auto-generated fallback scaffold command ({reason})")
    
    def _run_shell(command_text):
        try:
            result = subprocess.run(
                command_text,
                shell=True,
                capture_output=True,
                text=True,
                timeout=max(5, timeout_seconds),
                cwd=workspace_dir,
            )
            _stdout = (result.stdout or "").strip()
            _stderr = (result.stderr or "").strip()
            _parts = []
            if _stdout:
                _parts.append(_stdout)
            if _stderr:
                _parts.append(f"STDERR: {_stderr}")
            if not _parts:
                _parts.append("(no output)")
            return result.returncode == 0, "\n".join(_parts), _stderr
        except subprocess.TimeoutExpired:
            return False, f"Command timed out after {timeout_seconds}s", "timeout"
        except Exception as exc:
            _msg = f"Command execution error: {type(exc).__name__}: {exc}"
            return False, _msg, _msg
    
    if action_type != "external_call" and (not cmd) and _build_intent:
        _apply_autofallback("empty_command_for_build_intent")
    
    if action_type == "external_call":
        if not state.data.get("action_result"):
            state.data["action_result"] = f"External call routed separately: {state.data.get('interface_name', '')}"
        state.data["success"] = bool(state.data.get("success", False))
    elif not cmd:
        if not state.data.get("action_result"):
            state.data["action_result"] = "No executable command returned; kept planning result only."
        state.data["success"] = bool(state.data.get("success", False))
    elif any(tok in cmd_lower for tok in [
        "rm -rf",
        "git reset --hard",
        "mkfs",
        "dd if=",
        ":(){:|:&};:",
    ]):
        state.data["action_result"] = f"Blocked potentially destructive or long-running command: {cmd}"
        state.data["success"] = False
    elif cap != "external_enabled" and any(tok in cmd_lower for tok in [
        "npm install",
        "pnpm install",
        "yarn install",
        "pip install",
        "poetry install",
        "npx ",
        "npm create",
        "pnpm create",
        "yarn create",
        "create-react-app",
        "docker build",
        "docker run",
        "kubectl",
        "terraform apply",
        "vercel",
        "netlify",
        "heroku",
        "aws deploy",
    ]):
        state.data["action_result"] = f"Blocked by capability profile ({cap}): {cmd}"
        state.data["success"] = False
    elif any(tok in cmd_lower for tok in [
        "sudo ",
        "apt-get ",
        "yum ",
        "dnf ",
        "pacman ",
        "brew install",
        "choco install",
    ]):
        if action_type != "external_call" and _build_intent:
            _original = cmd
            state.data["autofallback_original_command"] = _original
            _apply_autofallback("blocked_privileged_or_package_manager_command")
            _ok, _msg, _stderr = _run_shell(cmd)
            state.data["action_result"] = (
                "Original command was replaced by a safe local scaffold.\n"
                f"Original: {_original}\n{_msg}"
            )
            state.data["success"] = _ok
        else:
            state.data["action_result"] = f"Blocked privileged or package-manager command: {cmd}"
            state.data["success"] = False
    else:
        _ok, _msg, _stderr = _run_shell(cmd)
        if _ok:
            state.data["action_result"] = _msg
            state.data["success"] = True
        else:
            _err_l = "\n".join([_msg, _stderr]).lower()
            _missing_tool = any(tok in _err_l for tok in [
                "command not found",
                "not found",
                "no such file or directory",
                "unable to locate package",
            ])
            if action_type != "external_call" and _build_intent and _missing_tool:
                _original = cmd
                _original_msg = _msg
                state.data["autofallback_original_command"] = _original
                _apply_autofallback("missing_tool_for_build_intent")
                _ok2, _msg2, _ = _run_shell(cmd)
                if _ok2:
                    state.data["action_result"] = (
                        "Original command failed due missing tooling; fallback scaffold executed.\n"
                        f"Original: {_original}\n"
                        f"Original output: {_original_msg}\n"
                        f"{_msg2}"
                    )
                    state.data["success"] = True
                else:
                    state.data["action_result"] = (
                        f"{_original_msg}\nFallback also failed: {_msg2}"
                    )
                    state.data["success"] = False
            else:
                state.data["action_result"] = _msg
                state.data["success"] = False

    def _assess_workspace_file_quality() -> dict:
        _skip_dirs = {
            ".git",
            ".live_runs",
            ".venv",
            "venv",
            "node_modules",
            "__pycache__",
        }
        _text_exts = {
            ".py", ".md", ".txt", ".json", ".yaml", ".yml", ".toml", ".ini", ".cfg",
            ".js", ".ts", ".tsx", ".jsx", ".html", ".css", ".sh", ".sql", ".csv",
        }
        _candidates = []
        try:
            for _root, _dirs, _names in os.walk(workspace_dir):
                _dirs[:] = [d for d in _dirs if d not in _skip_dirs]
                for _name in _names:
                    _lname = _name.lower()
                    if _lname.startswith("."):
                        continue
                    _is_candidate = (
                        _lname in {"readme", "readme.md", "readme.txt"}
                        or any(_lname.endswith(_ext) for _ext in _text_exts)
                    )
                    if not _is_candidate:
                        continue
                    _path = os.path.join(_root, _name)
                    _rel = os.path.relpath(_path, workspace_dir)
                    try:
                        _size = int(os.path.getsize(_path))
                    except Exception:
                        _size = -1
                    _candidates.append((_rel, _size))
        except Exception:
            return {
                "candidate_count": 0,
                "non_empty_count": 0,
                "empty_count": 0,
                "non_empty_files": [],
                "empty_files": [],
            }
        _candidates.sort(key=lambda t: t[0])
        _non_empty = [rel for rel, size in _candidates if size > 0]
        _empty = [rel for rel, size in _candidates if size == 0]
        return {
            "candidate_count": len(_candidates),
            "non_empty_count": len(_non_empty),
            "empty_count": len(_empty),
            "non_empty_files": _non_empty[:20],
            "empty_files": _empty[:20],
        }

    if action_type != "external_call" and _build_intent and bool(state.data.get("success", False)):
        _quality = _assess_workspace_file_quality()
        state.data["quality_file_check"] = _quality
        _candidate_count = int(_quality.get("candidate_count", 0) or 0)
        _non_empty_count = int(_quality.get("non_empty_count", 0) or 0)
        if _candidate_count > 0 and _non_empty_count == 0:
            _empty_preview = ", ".join(list(_quality.get("empty_files", []))[:5]) or "(unknown files)"
            _prior = str(state.data.get("action_result", "") or "").strip()
            _suffix = (
                "Quality gate failed: generated candidate files are all empty. "
                f"Examples: {_empty_preview}. Retry with real file contents."
            )
            state.data["action_result"] = f"{_prior}\n{_suffix}" if _prior else _suffix
            state.data["success"] = False
            state.data["quality_gate_failed"] = True
            state.data["quality_gate_reason"] = "all_candidate_files_empty"
        else:
            state.data["quality_gate_failed"] = False
            state.data.pop("quality_gate_reason", None)

    step_idx = state.data.get("current_step_idx", 0)
    state.data["key"] = f"step_{step_idx}"
    state.data["value"] = state.data.get("action_result", "")
    if state.data.get("_done"):
        return state

    return state


