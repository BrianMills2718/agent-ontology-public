def process_critic_gate(state):
    """
    Critic approved?
    """
    print(f"  → Critic approved?")

    # Gate: rating >= 7
    # Branch: rejected (rating < 7) → handle_rejection
    # Branch: approved (rating >= 7) → act

    if (state.data.get("rating", 0)) >= 7:
        print(f"    → approved (rating >= 7)")
        return "act"
    else:
        print(f"    → rejected (rating < 7)")
        return "handle_rejection"


def process_handle_rejection(state):
    """
    Handle Rejection
    Process critic feedback and retry or skip
    """
    print(f"  → Handle Rejection")

    # Logic from spec
    count = state.data.get("criticism_count", 0) + 1
    state.data["criticism_count"] = count
    max_retries = state.data.get("max_criticism_retries", 3)
    if count >= max_retries:
        print(f"    Max retries ({max_retries}) reached, proceeding anyway")
    else:
        state.data["feedback"] = state.data.get("improvements", "Try a different approach")
        print(f"    Retry {count}/{max_retries}: {state.data.get('improvements', '')[:100]}")
    if state.data.get("_done"):
        return state

    return state


def process_retry_or_proceed(state):
    """
    Retry or proceed?
    """
    print(f"  → Retry or proceed?")

    # Gate: criticism_count >= max_criticism_retries
    # Branch: under retry limit → think
    # Branch: at retry limit → act

    if (state.data.get("criticism_count", 0)) >= (state.data.get("max_criticism_retries", 0)):
        print(f"    → at retry limit")
        return "act"
    else:
        print(f"    → under retry limit")
        return "think"


def process_act(state):
    """
    Act
    Execute the approved action
    """
    print(f"  → Act")

    # Logic from spec
    action = state.data.get("proposed_action", "")
    print(f"    Executing: {action[:100]}")
    _atype = str(state.data.get("action_type", "") or "").strip().lower()
    if _atype in {"external", "externalcall"}:
        _atype = "external_call"
    elif _atype in {"none", "skip", "no_action"}:
        _atype = "none"
    elif _atype not in {"command", "external_call"}:
        _atype = "command"
    state.data["action_type"] = _atype
    if not isinstance(state.data.get("payload"), dict):
        state.data["payload"] = {}
    if _atype != "external_call":
        state.data["interface_name"] = str(state.data.get("interface_name", "") or "")
    state.data["use_external_call"] = _atype == "external_call"

    _telemetry = state.data.get("routing_telemetry", {})
    if not isinstance(_telemetry, dict):
        _telemetry = {}
    _telemetry.setdefault("policy_forced_external", 0)
    _telemetry.setdefault("heuristic_semantic_fallback", 0)
    _telemetry.setdefault("external_interface_repaired", 0)
    _telemetry.setdefault("semantic_fallback_dispatches", 0)
    state.data["routing_telemetry"] = _telemetry

    _policy = state.data.get("routing_policy", {})
    if not isinstance(_policy, dict):
        _policy = {}
    _policy_force = str(_policy.get("force_action_type") or _policy.get("action_type") or "").strip().lower()
    if _policy_force in {"external", "externalcall"}:
        _policy_force = "external_call"
    _policy_prefers_external = bool(_policy.get("prefer_external_call", False)) or _policy_force == "external_call"
    _policy_iface = str(_policy.get("preferred_interface") or _policy.get("interface_name") or "").strip()
    _policy_query = str(_policy.get("query") or "").strip()
    _policy_reason = str(_policy.get("reason") or "").strip()
    if _policy_prefers_external and _atype != "external_call":
        _payload = state.data.get("payload", {})
        if not isinstance(_payload, dict):
            _payload = {}
        _query_fallback = str(state.data.get("proposed_action") or state.data.get("current_step") or state.data.get("objective") or "").strip()
        _iface = _policy_iface or "semantic_search"
        if _iface in {"search", "lookup", "wikipedia_lookup", "web_fetch"}:
            _iface = "semantic_search"
        if _iface in {"mcp_tool_call"}:
            _iface = "mcp_call"
        if _iface in {"rpc_event"}:
            _iface = "rpc_emit"
        if _iface in {"semantic_search"}:
            _payload.setdefault("query", _policy_query or _query_fallback)
        elif _iface in {"mcp_call"}:
            _payload.setdefault("tool", "search")
            _payload.setdefault("args", {"query": _policy_query or _query_fallback})
        elif _iface in {"rpc_emit"}:
            _payload.setdefault("rpc_method", "delegate_retrieval")
            _payload.setdefault("payload", {"query": _policy_query or _query_fallback})
        state.data["action_type"] = "external_call"
        state.data["interface_name"] = _iface
        state.data["payload"] = _payload
        state.data["command"] = ""
        state.data["use_external_call"] = True
        state.data["routing_override_reason"] = "routing_policy_prefers_external_call"
        _telemetry["policy_forced_external"] = int(_telemetry.get("policy_forced_external", 0) or 0) + 1
        if _policy_reason:
            state.data["routing_override_policy_reason"] = _policy_reason
        _atype = "external_call"
        print(f"    Routing policy override: external_call via {_iface}")
    
    # Deterministic routing override:
    # For retrieval-oriented tasks, prefer typed external_call over shell path.
    _objective = str(state.data.get("objective", "") or "").lower()
    _step = str(state.data.get("current_step", "") or "").lower()
    _action = str(state.data.get("proposed_action", "") or "").lower()
    _reasoning = str(state.data.get("reasoning", "") or "").lower()
    _intent_text = " ".join([_objective, _step, _action, _reasoning])
    _focus_text = " ".join([_step, _action, _reasoning])
    _step_action_text = " ".join([_step, _action])
    _iface_current = str(state.data.get("interface_name", "") or "").strip()
    _iface_norm = _iface_current
    if _iface_norm in {"search", "lookup", "wikipedia_lookup", "web_fetch"}:
        _iface_norm = "semantic_search"
    if _iface_norm in {"mcp_tool_call"}:
        _iface_norm = "mcp_call"
    if _iface_norm in {"rpc_event"}:
        _iface_norm = "rpc_emit"
    if _iface_norm != _iface_current:
        state.data["interface_name"] = _iface_norm
    _supported_ifaces = {"semantic_search", "mcp_call", "rpc_emit"}
    _retrieval_markers = [
        "research", "look up", "lookup", "find information", "find sources",
        "search", "retrieve", "evidence", "citations", "reference",
        "wikipedia", "web", "mcp", "semantic", "what is", "who is",
    ]
    _build_markers = [
        "build", "implement", "create file", "write code", "refactor",
        "unit test", "pytest", "ci", "compile", "todo app", "application",
    ]
    _looks_retrieval = any(m in _intent_text for m in _retrieval_markers)
    _focus_retrieval = any(m in _focus_text for m in _retrieval_markers)
    _looks_build = any(m in _intent_text for m in _build_markers)
    _focus_build = any(m in _step_action_text for m in _build_markers)
    _current_cmd = str(state.data.get("command", "") or "").strip().lower()
    _cmd_is_retrievalish = any(tok in _current_cmd for tok in ["curl ", "wget ", "http://", "https://", "wikipedia", "search"])
    if _atype == "external_call" and _iface_norm not in _supported_ifaces:
        _repair_query = str(
            state.data.get("proposed_action")
            or state.data.get("current_step")
            or state.data.get("objective")
            or ""
        ).strip()
        if "mcp" in _intent_text:
            _repair_iface = "mcp_call"
        elif any(tok in _intent_text for tok in ["rpc", "event", "emit"]):
            _repair_iface = "rpc_emit"
        else:
            _repair_iface = "semantic_search"
        _payload = state.data.get("payload", {})
        if not isinstance(_payload, dict):
            _payload = {}
        if _repair_iface == "semantic_search":
            _payload.setdefault("query", _repair_query)
        elif _repair_iface == "mcp_call":
            _payload.setdefault("tool", "search")
            _payload.setdefault("args", {"query": _repair_query})
        elif _repair_iface == "rpc_emit":
            _payload.setdefault("rpc_method", "delegate_retrieval")
            _payload.setdefault("payload", {"query": _repair_query})
        state.data["interface_name"] = _repair_iface
        state.data["payload"] = _payload
        state.data["routing_override_reason"] = "external_call_interface_repaired"
        _telemetry["external_interface_repaired"] = int(_telemetry.get("external_interface_repaired", 0) or 0) + 1
        _iface_norm = _repair_iface
        print(f"    Routing repair: external_call interface normalized to {_repair_iface}")
    _should_override = (
        (not _policy_prefers_external)
        and
        (_atype != "external_call")
        and (not _current_cmd or _cmd_is_retrievalish)
        and (
            _focus_retrieval
            or (_looks_retrieval and (not _looks_build))
            or (_looks_retrieval and _cmd_is_retrievalish and (not _focus_build))
        )
    )
    if _should_override:
        _query = str(state.data.get("proposed_action") or state.data.get("current_step") or state.data.get("objective") or "").strip()
        _iface = str(state.data.get("interface_name", "") or "").strip()
        if not _iface:
            if "mcp" in _intent_text:
                _iface = "mcp_call"
            elif any(tok in _intent_text for tok in ["rpc", "event", "emit"]):
                _iface = "rpc_emit"
            else:
                _iface = "semantic_search"
        if _iface in {"mcp_tool_call"}:
            _iface = "mcp_call"
        if _iface in {"rpc_event"}:
            _iface = "rpc_emit"
        if _iface in {"search", "lookup", "wikipedia_lookup", "web_fetch"}:
            _iface = "semantic_search"
        if ("mcp" in _intent_text) and _iface in {"semantic_search"}:
            _iface = "mcp_call"
        _payload = state.data.get("payload", {})
        if not isinstance(_payload, dict):
            _payload = {}
        if _iface in {"semantic_search", "search", "web_fetch", "lookup", "wikipedia_lookup"}:
            _payload.setdefault("query", _query)
        elif _iface in {"mcp_call", "mcp_tool_call"}:
            _payload.setdefault("tool", "search")
            _payload.setdefault("args", {"query": _query})
        elif _iface in {"rpc_emit", "rpc_event"}:
            _payload.setdefault("rpc_method", "delegate_retrieval")
            _payload.setdefault("payload", {"query": _query})
        state.data["action_type"] = "external_call"
        state.data["interface_name"] = _iface
        state.data["payload"] = _payload
        state.data["command"] = ""
        state.data["use_external_call"] = True
        state.data["routing_override_reason"] = "retrieval_intent_prefers_external_call"
        _telemetry["heuristic_semantic_fallback"] = int(_telemetry.get("heuristic_semantic_fallback", 0) or 0) + 1
        state.data["semantic_fallback_count"] = int(state.data.get("semantic_fallback_count", 0) or 0) + 1
        _fallback_events = state.data.get("semantic_fallback_events", [])
        if not isinstance(_fallback_events, list):
            _fallback_events = []
        _fallback_events.append(
            {
                "from_action_type": _atype,
                "to_interface": _iface,
                "query": _query,
                "reason": "retrieval_intent_prefers_external_call",
            }
        )
        state.data["semantic_fallback_events"] = _fallback_events[-20:]
        print(f"    Routing override: external_call via {_iface}")
    if state.data.get("_done"):
        return state

    # Flatten nested dicts: promote schema fields to top-level state.data
    for _nested_val in list(state.data.values()):
        if isinstance(_nested_val, dict):
            for _nk, _nv in _nested_val.items():
                if _nk not in state.data:
                    state.data[_nk] = _nv

    # Invoke: Execute action
    executor_input = build_input(state, "ActionInput")
    executor_msg = json.dumps(executor_input, default=str)
    executor_raw = invoke_executor(executor_msg, output_schema="ActionResult")
    executor_result = parse_response(executor_raw, "ActionResult")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    executor_result = require_valid_output(executor_result, "ActionResult", 'Executor')
    state.schema_violations += len(validate_output(executor_result, "ActionResult"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    state.data["routing_policy"] = ""
    state.data["action_result"] = ""
    state.data["success"] = False
    state.data.update(executor_result)
    state.data["action_result_schema"] = executor_result
    state.data["act_result"] = executor_result
    print(f"    ← Executor: {executor_result}")

    return state


