    _LLM_CALL_SEQ += 1
    effective_task = task or f"{_DEFAULT_TASK}.embedding"
    if trace_id:
        effective_trace = trace_id
    else:
        effective_trace = f"{_TRACE_PREFIX}/embed/{_LLM_CALL_SEQ}"
    kwargs = {}
