def process_build_plan(state):
    """
    Build Plan
    Construct/refresh executable plan and acceptance criteria
    """
    print(f"  → Build Plan")

    # Invoke: plan objective
    planner_input = build_input(state, "PlanInput")
    planner_msg = json.dumps(planner_input, default=str)
    planner_raw = invoke_planner(planner_msg, output_schema="PlanState")
    planner_result = parse_response(planner_raw, "PlanState")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    planner_result = require_valid_output(planner_result, "PlanState", 'Planner')
    state.schema_violations += len(validate_output(planner_result, "PlanState"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    state.data["plan"] = []
    state.data["current_step_idx"] = 0
    state.data["total_steps"] = 0
    state.data["acceptance_criteria"] = []
    state.data.update(planner_result)
    state.data["plan_state"] = planner_result
    state.data["build_plan_result"] = planner_result
    print(f"    ← Planner: {planner_result}")

    return state


