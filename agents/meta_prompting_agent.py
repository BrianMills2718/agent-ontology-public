# Model override: set AGENT_ONTOLOGY_MODEL env var to override all agent models at runtime
_MODEL_OVERRIDE = os.environ.get("AGENT_ONTOLOGY_MODEL", "")
_OPENROUTER_API_KEY = os.environ.get("OPENROUTER_API_KEY", "")
_LLM_CALL_SEQ = 0
_TRACE_PREFIX = os.environ.get("AGENT_ONTOLOGY_TRACE_PREFIX", f"agent_ontology/{int(time.time())}")
_DEFAULT_TASK = os.environ.get("AGENT_ONTOLOGY_TASK", "agent_ontology_inference")
