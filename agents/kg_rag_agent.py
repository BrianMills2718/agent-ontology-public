def process_invoke_query_gen(state):
    """
    Invoke Query Generator
    """
    print(f"  → Invoke Query Generator")

    # Invoke: query_agent
    query_agent_input = build_input(state, "QueryGenInput")
    query_agent_msg = json.dumps(query_agent_input, default=str)
    query_agent_raw = invoke_query_agent(query_agent_msg, output_schema="KGQuery")
    query_agent_result = parse_response(query_agent_raw, "KGQuery")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    query_agent_result = require_valid_output(query_agent_result, "KGQuery", 'Query Generator')
    state.schema_violations += len(validate_output(query_agent_result, "KGQuery"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    state.data["entities"] = []
    state.data["relation"] = ""
    state.data.update(query_agent_result)
    state.data["kg_query"] = query_agent_result
    state.data["invoke_query_gen_result"] = query_agent_result
    print(f"    ← Query Generator: {query_agent_result}")

    return state


def process_execute_query(state):
    """
    Execute KG Query
    """
    print(f"  → Execute KG Query")

    # Read: 
    knowledge_graph_data = state.knowledge_graph.read()
    state.data["knowledge_graph"] = knowledge_graph_data

    # Logic from spec
    entities = state.data.get("entities", [])
    relation = state.data.get("relation", "")
    all_results = []
    for entity in entities:
        matches = state.knowledge_graph.read(entity)
        all_results.extend(matches)
    if relation and not all_results:
        all_results = state.knowledge_graph.read(relation)
    state.data["results"] = [str(r) for r in all_results] if all_results else ["No results found"]
    if state.data.get("_done"):
        return state

    return state


def process_synthesize_answer(state):
    """
    Synthesize Answer
    """
    print(f"  → Synthesize Answer")

    # Invoke: answer_agent
    answer_agent_input = build_input(state, "AnswerInput")
    answer_agent_msg = json.dumps(answer_agent_input, default=str)
    answer_agent_raw = invoke_answer_agent(answer_agent_msg, output_schema="AnswerOutput")
    answer_agent_result = parse_response(answer_agent_raw, "AnswerOutput")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    answer_agent_result = require_valid_output(answer_agent_result, "AnswerOutput", 'Answer Synthesizer')
    state.schema_violations += len(validate_output(answer_agent_result, "AnswerOutput"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    state.data["answer"] = ""
    state.data["sources"] = []
    state.data.update(answer_agent_result)
    state.data["answer_output"] = answer_agent_result
    state.data["synthesize_answer_result"] = answer_agent_result
    print(f"    ← Answer Synthesizer: {answer_agent_result}")

    return state


def process_emit_answer(state):
    """
    Emit Answer
    """
    print(f"  → Emit Answer")

    # Logic from spec
    state.data["_done"] = True
    if state.data.get("_done"):
        return state

    return state


