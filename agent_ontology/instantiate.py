def _check_invoke_reachable(process, has_agent_invoke):
    """Refuse a step that sets `_done = True` unconditionally before its agent call.

    The generated step returns as soon as `_done` is set after the logic, so such
    an invoke is dead code: Plan-and-Solve's synthesizer was never called and
    its final_answer stayed empty.
    """
    import ast
    import textwrap
    if not has_agent_invoke or not process.get("logic"):
        return
    body = ast.parse("def _step():\n" + textwrap.indent(process["logic"], "    ")).body[0].body
    for node in body:
        if (isinstance(node, ast.Assign) and len(node.targets) == 1
                and ast.unparse(node.targets[0]) == "state.data['_done']"
                and ast.unparse(node.value) == "True"):
            raise ValueError(
                f"process {process['id']}: sets state.data['_done'] = True unconditionally, "
                "so its agent invocation can never run; end the run with an edge instead")


# Process types the generator emits real code for. Anything else (spawn,
# formal_translation, symbolic_inference, search, protocol, error_handler, and
# any future type) raises when reached: these used to be emitted as
# `print("[SPAWN] Would create sub-agent ...")` or an empty body followed by a
# normal return, so map_reduce never mapped, pddl_planner never planned, and the
# run still reported a clean exit.
_IMPLEMENTED_PROCESS_TYPES = frozenset({"step", "gate", "checkpoint", "policy"})


def _unimplemented_raise(agent_name, process):
    msg = (f"{agent_name}: process '{process['id']}' ({process.get('type')}) has no generated "
           f"implementation, so this agent cannot run past it")
    return f"raise NotImplementedError({msg!r})"


def _policy_body(process, backend):
    """A policy is not enforced by generated code. Say so on every pass and
    record it in state, rather than returning as though it had been applied."""
    pid = process["id"]
    label = process.get("label", pid)
    effect = process.get("effect", "")
    note = f"    [POLICY] NOT ENFORCED: {label} (effect={effect}) is declarative only in generated code"
    lines = [f'    print({note!r})']
    if backend == "custom":
        lines += [f'    state.data["_unenforced_policies"] = list(state.data.get("_unenforced_policies") or []) + [{pid!r}]',
                  '    return state']
    else:
        lines += [f'    updates["_unenforced_policies"] = list(state.get("_unenforced_policies") or []) + [{pid!r}]',
                  '    return updates']
    return lines


def unimplemented_reachable_processes(spec):
    """(process id, type) for every process with no generated implementation
    that the run can reach from `entry_point`. A non-empty result means the
    generated agent raises NotImplementedError on that path, so it cannot be
    run or scored."""
    procs = {p["id"]: p for p in spec.get("processes", [])}
    adj = {}
    for e in spec.get("edges", []):
        if e.get("type") in ("flow", "loop", "branch", "error", "handoff"):
            adj.setdefault(e.get("from"), set()).add(e.get("to"))
    for p in procs.values():
        for b in p.get("branches", []) or []:
            adj.setdefault(p["id"], set()).add(b.get("target"))
    seen, stack = set(), [spec.get("entry_point")]
    while stack:
        node = stack.pop()
        if node is None or node in seen or node not in procs:
            continue
        seen.add(node)
        stack.extend(adj.get(node, ()))
    return [(pid, procs[pid].get("type")) for pid in procs
            if pid in seen and procs[pid].get("type") not in _IMPLEMENTED_PROCESS_TYPES]


