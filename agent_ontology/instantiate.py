_TOOL_DECISION_FIELDS = frozenset({"tool_name", "tool_input", "tool_calls"})
# ...and the keys it owns: its input batch and the results it writes.
_TOOL_EXCHANGE_KEYS = (("tool_calls", "[]"), ("observation", '""'), ("tool_results", "[]"))

