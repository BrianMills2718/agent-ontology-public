def _safe_name(s):
    return s.replace("-", "_").replace(" ", "_").replace(".", "_")


def _escape_triple(s):
    return s.replace('"""', '\\"\\"\\"')


def _camel_to_snake(name):
    """Convert CamelCase to snake_case. E.g., SecurityReview -> security_review."""
    import re
    s = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    s = re.sub(r'([a-z\d])([A-Z])', r'\1_\2', s)
    return s.lower()


def _field_default_literal(ftype):
    """Python source literal for a schema field's default value, keyed by its
    declared type. Used to reset a schema's fields before merging a freshly
    parsed LLM response, so a field the LLM omitted this call (e.g. an
    optional `tool_name` on a thought-only ReAct step) reverts to its
    schema-declared default instead of silently retaining whatever value a
    PRIOR invocation of the same schema happened to leave behind."""
    if ftype.startswith("list"):
        return "[]"
    if ftype == "integer":
        return "0"
    if ftype == "boolean":
        return "False"
    return '""'



def _schema_field_names(schema):
    return [f.get("name") for f in schema.get("fields", [])]


def _persisted_record(logic, schema, process_id):
    """The record a step's logic builds for a schema it also persists, if any.

    A store write used to rebuild its entry from state by field name, while the
    logic appended its own local record to an in-memory list (ReAct's `step`,
    Debate's `turn`, Reflexion's `episode`). Whenever the local record computed
    or renamed a value -- the synthesized "tool[input]" action, "side": "con",
    trial -> trial_number -- the persisted entry disagreed with the kept one.

    Returns a source expression -- the local variable name, or
    `state.data["key"]` for `state.data["key"] = {...}` -- for the last top-level dict literal whose
    string keys cover every schema field; None if there is none. Two different
    candidate targets are ambiguous and fail generation loudly.
    """
    import ast
    import textwrap
    if not logic:
        return None
    fields = set(_schema_field_names(schema))
    wrapped = "def _step():\n" + textwrap.indent(logic, "    ")
    body = ast.parse(wrapped).body[0].body
    targets = []
    for node in body:
        if not (isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.value, ast.Dict)):
            continue
        keys = {k.value for k in node.value.keys if isinstance(k, ast.Constant) and isinstance(k.value, str)}
        if not fields <= keys:
            continue
        tgt = node.targets[0]
        if isinstance(tgt, ast.Name):
            targets.append(tgt.id)  # local variable: usable as-is
        elif (isinstance(tgt, ast.Subscript) and isinstance(tgt.slice, ast.Constant)
              and ast.unparse(tgt.value) == "state.data"):
            targets.append(f'state.data["{tgt.slice.value}"]')
    if len(set(targets)) > 1:
        raise ValueError(f"process {process_id}: ambiguous persisted record, candidates {targets}")
    return targets[-1] if targets else None


