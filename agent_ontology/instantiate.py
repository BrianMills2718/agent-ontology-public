import argparse

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))


def load_yaml(path):
    with open(path) as f:
        return yaml.safe_load(f)


def generate_agent(spec, persistent_stores=False):
    """Generate a complete Python agent script from a spec."""
    name = spec["name"]
    entities = spec.get("entities", [])
    processes = spec.get("processes", [])
    edges = spec.get("edges", [])
    schemas = spec.get("schemas", [])
    entry_point = spec.get("entry_point")

    # Index everything
    entity_map = {e["id"]: e for e in entities}
    process_map = {p["id"]: p for p in processes}
    schema_map = {s["name"]: s for s in schemas}

    # Build adjacency: for each process, what flows/branches out?
    flow_graph = {}
    for e in edges:
        if e["type"] in ("flow", "branch"):
            src = e["from"]
            flow_graph.setdefault(src, []).append((e["to"], e))

    # Build invoke map: for each process, what entities does it invoke?
    invoke_map = {}
    for e in edges:
        if e["type"] == "invoke":
            invoke_map.setdefault(e["from"], []).append((e["to"], e))

    # Build store access: for each process, what stores does it read/write?
    store_access = {}
    for e in edges:
        if e["type"] in ("read", "write"):
            store_access.setdefault(e["from"], []).append((e["to"], e["type"], e))

    # Build channel access: publish = write to channel, subscribe = read from channel
    # subscribe edges: from=channel, to=step/agent → step reads from channel
    # publish edges: from=step/agent, to=channel → step writes to channel
    channel_access = {}
    for e in edges:
        if e["type"] == "publish":
            channel_access.setdefault(e["from"], []).append((e["to"], "publish", e))
        elif e["type"] == "subscribe":
            channel_access.setdefault(e["to"], []).append((e["from"], "subscribe", e))

    # Build loop map
    loop_map = {}
    for e in edges:
        if e["type"] == "loop":
            loop_map[e["from"]] = (e["to"], e)

    # Categorize entities
    agents = [e for e in entities if e["type"] == "agent"]
    stores = [e for e in entities if e["type"] == "store"]
    channels = [e for e in entities if e["type"] == "channel"]

    # ── Generate code ──
    lines = []
    w = lines.append

    # Header
    w('#!/usr/bin/env python3')
    w(f'"""')
    w(f'{name} — Generated by Agent Ontology Instantiation Engine')
    w(f'Spec: {spec.get("description", "")}')
    w(f'"""')
    w('')
    w('import json')
    w('import os')
    w('import sys')
    w('import time')
    w('from datetime import datetime')
    w('')

    # ── Trace log ──
    w('# ═══════════════════════════════════════════════════════════')
    w('# Trace Log')
    w('# ═══════════════════════════════════════════════════════════')
    w('')
    w('TRACE = []')
    w('')
    w('def trace_call(agent_label, model, system_prompt, user_message, response, duration_ms):')
    w('    entry = {')
    w('        "timestamp": datetime.now().isoformat(),')
    w('        "agent": agent_label,')
    w('        "model": model,')
    w('        "system_prompt": system_prompt,')
    w('        "user_message": user_message,')
    w('        "response": response,')
    w('        "duration_ms": duration_ms,')
    w('    }')
    w('    TRACE.append(entry)')
    w('    print(f"    [{agent_label}] ({model}, {duration_ms}ms)")')
    w('    print(f"      IN:  {user_message[:300]}")')
    w('    print(f"      OUT: {response[:300]}")')
    w('')
    w('')
    w('def dump_trace(path="trace.json", iterations=0, clean_exit=True):')
    w('    # Compute metrics')
    w('    total_ms = sum(e["duration_ms"] for e in TRACE)')
    w('    agents_used = list(set(e["agent"] for e in TRACE))')
    w('    schema_ok = 0')
    w('    for e in TRACE:')
    w('        try:')
    w('            r = e["response"].strip()')
    w('            if r.startswith("```"): r = "\\n".join(r.split("\\n")[1:-1])')
    w('            json.loads(r if r.startswith("{") else r[r.find("{"):r.rfind("}")+1])')
    w('            schema_ok += 1')
    w('        except (json.JSONDecodeError, ValueError):')
    w('            pass')
    w('    est_input_tokens = sum(len(e.get("user_message",""))//4 for e in TRACE)')
    w('    est_output_tokens = sum(len(e.get("response",""))//4 for e in TRACE)')
    w('    metrics = {')
    w('        "total_llm_calls": len(TRACE),')
    w('        "total_duration_ms": total_ms,')
    w('        "avg_call_ms": total_ms // max(len(TRACE), 1),')
    w('        "iterations": iterations,')
    w('        "clean_exit": clean_exit,')
    w('        "agents_used": agents_used,')
    w('        "schema_compliance": f"{schema_ok}/{len(TRACE)}",')
    w('        "est_input_tokens": est_input_tokens,')
    w('        "est_output_tokens": est_output_tokens,')
    w('    }')
    w('    output = {"metrics": metrics, "trace": TRACE}')
    w('    with open(path, "w") as f:')
    w('        json.dump(output, f, indent=2)')
    w('    print(f"\\nTrace written to {path} ({len(TRACE)} calls, {total_ms}ms total)")')
    w('    print(f"  Schema compliance: {schema_ok}/{len(TRACE)}, est tokens: ~{est_input_tokens}in/~{est_output_tokens}out")')
    w('    return metrics')
    w('')

    # ── LLM call infrastructure ──
    w('# ═══════════════════════════════════════════════════════════')
    w('# LLM Call Infrastructure')
    w('# ═══════════════════════════════════════════════════════════')
    w('')
    w('# Model override: set AGENT_ONTOLOGY_MODEL env var to override all agent models at runtime')
    w('_MODEL_OVERRIDE = os.environ.get("AGENT_ONTOLOGY_MODEL", "")')
    w('_OPENROUTER_API_KEY = os.environ.get("OPENROUTER_API_KEY", "")')
    w('_LLM_CALL_SEQ = 0')
    w('_TRACE_PREFIX = os.environ.get("AGENT_ONTOLOGY_TRACE_PREFIX", f"agent_ontology/{int(time.time())}")')
    w('_DEFAULT_TASK = os.environ.get("AGENT_ONTOLOGY_TASK", "agent_ontology_inference")')
    w('_LLM_CLIENT_INFO_PRINTED = False')
    w('')
    w('')
    w('def _openrouter_model_id(model):')
    w('    """Map spec model names to OpenRouter model IDs (provider/model format)."""')
    w('    if "/" in model:')
    w('        return model  # already in provider/model format')
    w('    if model.startswith("gemini"):')
    w('        return f"google/{model}"')
    w('    if model.startswith("claude") or model.startswith("anthropic"):')
    w('        return f"anthropic/{model}"')
    w('    if model.startswith("gpt") or model.startswith("o1") or model.startswith("o3"):')
    w('        return f"openai/{model}"')
    w('    return model  # pass through as-is')
    w('')
    w('')
    w('def _normalize_temperature(model, temperature):')
    w('    """Normalize model-specific temperature constraints for llm_client/litellm."""')
    w('    try:')
    w('        model_l = str(model).lower()')
    w('    except Exception:')
    w('        model_l = ""')
    w('    # gpt-5 family currently only supports temperature=1 in litellm routing.')
    w('    if "gpt-5" in model_l:')
    w('        return 1')
    w('    return temperature')
    w('')
    w('')
    w('def call_llm(model, system_prompt, user_message, temperature=0.7, max_tokens=8192, retries=3, task=None, trace_id=None, max_budget=None):')
    w('    """Unified LLM call path via llm_client with observability tags."""')
    w('    global _LLM_CALL_SEQ')
    w('    if _MODEL_OVERRIDE:')
    w('        model = _MODEL_OVERRIDE')
    w('    temperature = _normalize_temperature(model, temperature)')
    w('    _LLM_CALL_SEQ += 1')
    w('')
    w('    # Enforce llm_client observability contract by default.')
    w('    effective_task = task or _DEFAULT_TASK')
    w('    if trace_id:')
    w('        effective_trace = trace_id')
    w('    else:')
    w('        effective_trace = f"{_TRACE_PREFIX}/{_LLM_CALL_SEQ}"')
    w('    if max_budget is None:')
    w('        raw_budget = os.environ.get("AGENT_ONTOLOGY_MAX_BUDGET_USD", "0")')
    w('        try:')
    w('            effective_budget = float(raw_budget)')
    w('        except ValueError:')
    w('            effective_budget = 0.0')
    w('    else:')
    w('        effective_budget = float(max_budget)')
    w('')
    w('    messages = [')
    w('        {"role": "system", "content": system_prompt},')
    w('        {"role": "user", "content": user_message},')
    w('    ]')
    w('')
    w('    kwargs = {')
    w('        "temperature": temperature,')
    w('        "max_tokens": max_tokens,')
    w('        "num_retries": retries,')
    w('    }')
    w('    if _OPENROUTER_API_KEY:')
    w('        model = _openrouter_model_id(model)')
    w('        kwargs["api_base"] = "https://openrouter.ai/api/v1"')
    w('        kwargs["api_key"] = _OPENROUTER_API_KEY')
    w('')
    w('    try:')
    w('        global _LLM_CLIENT_INFO_PRINTED')
    w('        try:')
    w('            from llm_client import call_llm as llm_client_call')
    w('            import llm_client as _llm_client_pkg')
    w('        except ImportError:')
    w('            # Support monorepo layout where package lives at llm_client/llm_client')
    w('            from llm_client import call_llm as llm_client_call')
    w('            import llm_client.llm_client as _llm_client_pkg')
    w('        if not _LLM_CLIENT_INFO_PRINTED:')
    w('            _llm_path = getattr(_llm_client_pkg, "__file__", "unknown")')
    w('            _llm_version = getattr(_llm_client_pkg, "__version__", "n/a")')
    w('            print(f"    [RUNTIME] llm_client module={_llm_path} version={_llm_version}")')
    w('            _LLM_CLIENT_INFO_PRINTED = True')
    w('        result = llm_client_call(')
    w('            model,')
    w('            messages,')
    w('            task=effective_task,')
    w('            trace_id=effective_trace,')
    w('            max_budget=effective_budget,')
    w('            **kwargs,')
    w('        )')
    w('        return result.content or ""')
    w('    except Exception as e:')
    w('        # Fail loudly. Returning a stub reply here let the agent walk its graph on')
    w('        # empty fields and exit 0 with a fallback "answer", so a provider outage was')
    w('        # scored as a wrong answer. llm_client already retried (num_retries).')
    w('        print(f"    [FAIL] {type(e).__name__}: {e}")')
    w('        raise')
    w('')
    w('')
    w('def call_embedding(texts, model="text-embedding-3-small", provider="openai", task=None, trace_id=None):')
    w('    """Generate embeddings via llm_client for a list of texts."""')
    w('    global _LLM_CALL_SEQ')
    w('    global _LLM_CLIENT_INFO_PRINTED')
    w('    if isinstance(texts, str):')
    w('        texts = [texts]')
    w('    _LLM_CALL_SEQ += 1')
    w('    effective_task = task or f"{_DEFAULT_TASK}.embedding"')
    w('    if trace_id:')
    w('        effective_trace = trace_id')
    w('    else:')
    w('        effective_trace = f"{_TRACE_PREFIX}/embed/{_LLM_CALL_SEQ}"')
    w('    kwargs = {}')
    w('    effective_model = model')
    w('    if _OPENROUTER_API_KEY:')
    w('        effective_model = _openrouter_model_id(model)')
    w('        kwargs["api_base"] = "https://openrouter.ai/api/v1"')
    w('        kwargs["api_key"] = _OPENROUTER_API_KEY')
    w('    try:')
    w('        try:')
    w('            from llm_client import embed as llm_client_embed')
    w('            import llm_client as _llm_client_pkg')
    w('        except ImportError:')
    w('            # Support monorepo layout where package lives at llm_client/llm_client')
    w('            from llm_client import embed as llm_client_embed')
    w('            import llm_client.llm_client as _llm_client_pkg')
    w('        if not _LLM_CLIENT_INFO_PRINTED:')
    w('            _llm_path = getattr(_llm_client_pkg, "__file__", "unknown")')
    w('            _llm_version = getattr(_llm_client_pkg, "__version__", "n/a")')
    w('            print(f"    [RUNTIME] llm_client module={_llm_path} version={_llm_version}")')
    w('            _LLM_CLIENT_INFO_PRINTED = True')
    w('        result = llm_client_embed(')
    w('            effective_model,')
    w('            texts,')
    w('            task=effective_task,')
    w('            trace_id=effective_trace,')
    w('            **kwargs,')
    w('        )')
    w('        return result.embeddings')
    w('    except Exception as e:')
    w('        # Fail loudly: `[[] for _ in texts]` is truthy, so callers treated it as real')
    w('        # embeddings. A store that wants a fallback catches this and says so.')
    w('        print(f"    [FAIL] Embedding call failed: {type(e).__name__}: {e}")')
    w('        raise')
    w('')
    w('')
    w('# ── External interface adapter (deterministic/live/llm_mock) ──')
    w('try:')
    w('    from agent_ontology.external_interfaces import dispatch_external_interface as _dispatch_external_interface')
    w('except Exception:')
    w('    try:')
    w('        import pathlib as _pathlib')
    w('        _repo_root = _pathlib.Path(__file__).resolve().parents[1]')
    w('        _pkg_root = _repo_root / "agent_ontology"')
    w('        if str(_repo_root) not in sys.path:')
    w('            sys.path.insert(0, str(_repo_root))')
    w('        if str(_pkg_root) not in sys.path:')
    w('            sys.path.insert(0, str(_pkg_root))')
    w('        sys.modules.pop("agent_ontology.external_interfaces", None)')
    w('        sys.modules.pop("agent_ontology", None)')
    w('        from agent_ontology.external_interfaces import dispatch_external_interface as _dispatch_external_interface')
    w('    except Exception:')
    w('        _dispatch_external_interface = None')
    w('')
    w('def _external_tool_dispatch(interface_name, payload):')
    w('    """Dispatch tool calls through typed external adapter when configured."""')
    w('    if _dispatch_external_interface is None:')
    w('        return {"handled": False, "ok": True}')
    w('    try:')
    w('        return _dispatch_external_interface(')
    w('            interface_name,')
    w('            payload=payload if isinstance(payload, dict) else {"value": payload},')
    w('            context={"source": "generated_tool"}')
    w('        )')
    w('    except Exception as e:')
    w('        return {"handled": True, "ok": False, "error": f"{type(e).__name__}: {e}"}')
    w('')
    w('# ── Shared local tool runtime adapter ──')
    w('try:')
    w('    from agent_ontology.tool_runtime import dispatch_tool_operation as _dispatch_tool_operation')
    w('except Exception:')
    w('    try:')
    w('        import pathlib as _pathlib')
    w('        _repo_root = _pathlib.Path(__file__).resolve().parents[1]')
    w('        _pkg_root = _repo_root / "agent_ontology"')
    w('        if str(_repo_root) not in sys.path:')
    w('            sys.path.insert(0, str(_repo_root))')
    w('        if str(_pkg_root) not in sys.path:')
    w('            sys.path.insert(0, str(_pkg_root))')
    w('        sys.modules.pop("agent_ontology.tool_runtime", None)')
    w('        sys.modules.pop("agent_ontology", None)')
    w('        from agent_ontology.tool_runtime import dispatch_tool_operation as _dispatch_tool_operation')
    w('    except Exception:')
    w('        _dispatch_tool_operation = None')
    w('')
    w('def _runtime_tool_dispatch(tool_name, input_text):')
    w('    """Dispatch generic tool calls via shared runtime tool library."""')
    w('    if _dispatch_tool_operation is None:')
    w('        return f"[tool {tool_name} unavailable: tool_runtime import failed]"')
    w('    try:')
    w('        _result = _dispatch_tool_operation(tool_name, input_text)')
    w('    except Exception as e:')
    w('        return f"[tool {tool_name} runtime error: {type(e).__name__}: {e}]"')
    w('    if not isinstance(_result, dict):')
    w('        return str(_result)')
    w('    _handled = bool(_result.get("handled", False))')
    w('    _ok = bool(_result.get("ok", True))')
    w('    _out = str(_result.get("output", "") or "")')
    w('    if _handled and _ok:')
    w('        return _out')
    w('    if _handled and not _ok:')
    w('        _err = _result.get("error")')
    w('        return str(_err) if _err else _out')
    w('    return f"[tool {tool_name} not implemented for input: {input_text}]"')
    w('')

    # ── Schema registry ──
    w('# ═══════════════════════════════════════════════════════════')
    w('# Schema Registry')
    w('# ═══════════════════════════════════════════════════════════')
    w('')
    w('SCHEMAS = {')
    for s in schemas:
        sname = s["name"]
        fields = s.get("fields", [])
        desc = s.get("description", "")
        field_strs = []
        for f in fields:
            fname = f["name"].replace('"', '\\"')
            ftype = f["type"].replace('"', '\\"')
            _opt = ', "optional": True' if f.get("optional") else ''
            field_strs.append(f'{{"name": "{fname}", "type": "{ftype}"{_opt}}}')
        w(f'    "{sname}": {{')
        w(f'        "description": """{_escape_triple(desc)}""",')
        w(f'        "fields": [{", ".join(field_strs)}],')
        w(f'    }},')
    w('}')
    w('')

    # ── Schema helpers ──
    w('')
    _emit_schema_helpers(w)
    w('')
    w('')
    w('def build_input(state, schema_name):')
    w('    """Build an input dict for an agent call using schema field names.')
    w('    Pulls matching keys from state.data, checking both flat keys and')
    w('    values nested inside dict entries (e.g. state.data["xxx_input"]["field"])."""')
    w('    schema = SCHEMAS.get(schema_name)')
    w('    if not schema:')
    w('        return state.data')
    w('    result = {}')
    w('    for field in schema["fields"]:')
    w('        fname = field["name"]')
    w('        if fname in state.data:')
    w('            result[fname] = state.data[fname]')
    w('        else:')
    w('            # Search nested dicts in state.data for the field')
    w('            for _k, _v in state.data.items():')
    w('                if isinstance(_v, dict) and fname in _v:')
    w('                    result[fname] = _v[fname]')
    w('                    break')
    w('    return result')
    w('')
    w('')
    w('def output_instruction(schema_name):')
    w('    """Generate a JSON output instruction string for the LLM."""')
    w('    schema = SCHEMAS.get(schema_name)')
    w('    if not schema:')
    w('        return ""')
    w('    fields = ", ".join(f\'"{f["name"]}": <{f["type"]}>\' for f in schema["fields"])')
    w('    return f"\\n\\nRespond with ONLY valid JSON matching this schema: {{{fields}}}"')
    w('')
    w('')
    w('def parse_response(response, schema_name):')
    w('    """Parse an LLM response according to an output schema.')
    w('    Returns a dict of field values, or {"raw": response} if parsing fails."""')
    w('    import re as _re')
    w('    text = response.strip()')
    w('    # Handle markdown code blocks')
    w('    if text.startswith("```"):')
    w('        lines = text.split("\\n")')
    w('        lines = lines[1:]  # skip ```json')
    w('        if lines and lines[-1].strip() == "```":')
    w('            lines = lines[:-1]')
    w('        text = "\\n".join(lines)')
    w('    # Attempt 1: direct parse')
    w('    try:')
    w('        parsed = json.loads(text)')
    w('        if isinstance(parsed, dict):')
    w('            return parsed')
    w('        return {"value": parsed}')
    w('    except json.JSONDecodeError:')
    w('        pass')
    w('    # Attempt 2: extract JSON object from prose')
    w('    start = text.find("{")')
    w('    end = text.rfind("}") + 1')
    w('    if start >= 0 and end > start:')
    w('        candidate = text[start:end]')
    w('        try:')
    w('            return json.loads(candidate)')
    w('        except json.JSONDecodeError:')
    w('            pass')
    w('        # Attempt 3: fix trailing commas')
    w('        fixed = _re.sub(r",\\s*}", "}", candidate)')
    w('        fixed = _re.sub(r",\\s*]", "]", fixed)')
    w('        try:')
    w('            return json.loads(fixed)')
    w('        except json.JSONDecodeError:')
    w('            pass')
    w('        # Attempt 4: find matching braces (handle nested)')
    w('        depth = 0')
    w('        for i, ch in enumerate(text[start:], start):')
    w('            if ch == "{": depth += 1')
    w('            elif ch == "}": depth -= 1')
    w('            if depth == 0:')
    w('                try:')
    w('                    return json.loads(text[start:i+1])')
    w('                except json.JSONDecodeError:')
    w('                    break')
    w('    return {"raw": response}')
    w('')

    # ── Store classes ──
    if stores:
        w('')
        w('# ═══════════════════════════════════════════════════════════')
        w('# Stores')
        w('# ═══════════════════════════════════════════════════════════')
        # Emit ChromaDB vector store helper if any store is vector type
        has_vector = any(s.get("store_type") == "vector" for s in stores)
        if has_vector:
            w('')
            if persistent_stores:
                w('# ── ChromaDB Vector Store (persistent) ──')
                w('try:')
                w('    import chromadb')
                w('    _chroma_client = chromadb.PersistentClient(path=os.path.join(os.path.dirname(__file__), ".store_data", "chroma"))')
                w('    _USE_CHROMA = True')
                w('except ImportError:')
                w('    _USE_CHROMA = False')
            else:
                w('# ── ChromaDB Vector Store (falls back to in-memory list) ──')
                w('try:')
                w('    import chromadb')
                w('    _chroma_client = chromadb.Client()')
                w('    _USE_CHROMA = True')
                w('except ImportError:')
                w('    _USE_CHROMA = False')
            w('')
            w('')
            w('class _ChromaVectorStore:')
            w('    """Vector store backed by ChromaDB with real embedding support."""')
            w('    def __init__(self, name, embedding_model=None, embedding_provider=None):')
            w('        self._fallback = []')
            w('        self._collection = None')
            w('        self._embedding_model = embedding_model')
            w('        self._embedding_provider = embedding_provider')
            w('        if _USE_CHROMA:')
            w('            self._collection = _chroma_client.get_or_create_collection(name)')
            w('            print(f"    [ChromaDB] collection \'{name}\' ready")')
            w('            if embedding_model:')
            w('                print(f"    [Embeddings] using {embedding_model} ({embedding_provider or \'auto\'})")')
            w('        else:')
            w('            print(f"    [VectorStore] using in-memory fallback (pip install chromadb for semantic search)")')
            w('')
            w('    def _embed(self, texts):')
            w('        """Generate embeddings if an embedding model is configured."""')
            w('        if not self._embedding_model:')
            w('            return None')
