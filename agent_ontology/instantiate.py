def _transform_logic_line_lg(line, store_names=None):
    """Transform a logic line from custom backend format to LangGraph format.

    state.data["x"] = val    →  updates["x"] = val
    state.data["x"] += val   →  updates["x"] = _st_view.get("x", 0) + val
    state.data["x"]["k"] = v →  updates["x"] = copy of x; updates["x"]["k"] = v
    state.data.get("x")      →  _st_view.get("x")
    state.data["x"]          →  _st_view.get("x", ...) for reads
    (_st_view = ChainMap(updates, state): reads see this node's earlier writes)
    state.{store_name}        →  _store_{store_name}  (module-level singletons)
    """
    import re

    # Store references: state.{store_name} → _store_{store_name}
    if store_names:
        for sname in store_names:
            line = re.sub(rf'\bstate\.{re.escape(sname)}\b', f'_store_{sname}', line)

    # Augmented assignment: state.data["key"] += value (or -=, *=, etc.)
    aug_match = re.match(r'^(\s*)state\.data\[(["\'][^"\']+["\'])\]\s*(\+=|-=|\*=|/=)\s*(.+)$', line)
    if aug_match:
        indent = aug_match.group(1)
        key = aug_match.group(2)
        op = aug_match.group(3)  # e.g., +=
        value = aug_match.group(4)
        base_op = op[0]  # +, -, *, /
        value = _transform_logic_rhs_lg(value)
        return f'{indent}updates[{key}] = _st_view.get({key}, 0) {base_op} {value}'

    # Whole-dict mutation: state.data.update(x) / state.data.pop("k"). Both used
    # to become `dict(state).update(x)` -- a write into a throwaway copy, so the
    # LangGraph node silently dropped it (Livekit's normalized decision).
    update_match = re.match(r'^(\s*)state\.data\.update\((.+)\)\s*$', line)
    if update_match:
        return f'{update_match.group(1)}updates.update({_transform_logic_rhs_lg(update_match.group(2))})'
    pop_match = re.match(r'^(\s*)state\.data\.pop\((["\'][^"\']+["\'])(?:\s*,[^)]*)?\)\s*$', line)
    if pop_match:
        # A LangGraph node cannot delete a channel; None is what .get() returns either way.
        return f'{pop_match.group(1)}updates[{pop_match.group(2)}] = None'

    # Nested write: state.data["key"][sub]... = value. Previously this fell
    # through to the read rewrite and became `state.get('key', '')[sub] = value`:
    # a write into the input state (or into '' when the key was missing).
    nested_match = re.match(r'^(\s*)state\.data\[(["\'][^"\']+["\'])\]((?:\[[^\]]+\])+)\s*=(?!=)\s*(.+)$', line)
    if nested_match:
        indent = nested_match.group(1)
        key = nested_match.group(2)
        subs = _transform_logic_rhs_lg(nested_match.group(3))
        value = _transform_logic_rhs_lg(nested_match.group(4))
        return (f'{indent}updates[{key}] = _copy_container(_st_view.get({key})); '
                f'updates[{key}]{subs} = {value}')

    # Simple assignment: state.data["key"] = value
    assign_match = re.match(r'^(\s*)state\.data\[(["\'][^"\']+["\'])\]\s*=\s*(.+)$', line)
    if assign_match:
        indent = assign_match.group(1)
        key = assign_match.group(2)
        value = assign_match.group(3)
        value = _transform_logic_rhs_lg(value)
        return f'{indent}updates[{key}] = {value}'

    # Method calls on state.data["key"] like .append(v): state.data["x"].append(y)
    method_match = re.match(r'^(\s*)state\.data\[(["\'][^"\']+["\'])\]\.(append|extend|insert|pop|remove)\((.+)\)\s*$', line)
    if method_match:
        indent = method_match.group(1)
        key = method_match.group(2)
        method = method_match.group(3)
        args = method_match.group(4)
        args = _transform_logic_rhs_lg(args)
        if method == "append":
            return f'{indent}_list = list(_st_view.get({key}, []) or []); _list.append({args}); updates[{key}] = _list'
        elif method == "extend":
            return f'{indent}_list = list(_st_view.get({key}, []) or []); _list.extend({args}); updates[{key}] = _list'
        else:
            return f'{indent}_tmp = list(_st_view.get({key}, []) or []); _tmp.{method}({args}); updates[{key}] = _tmp'

    # state.data.get("key", default) → state.get("key", default)
    line = re.sub(r'state\.data\.get\(', '_st_view.get(', line)

    # state.data["key"] in read context → state.get("key", "")
    line = re.sub(r'state\.data\[(["\'][^"\']+["\'])\]', _single_quoted, line)

    # state.data (bare reference) → dict(state)
    line = re.sub(r'\bstate\.data\b', 'dict(_st_view)', line)

    return line


def _single_quoted(match):
    """Rewrite a captured string literal to single quotes.

    These substitutions land inside generated f-strings. A double-quoted
    literal nested in a double-quoted f-string only parses on Python 3.12+
    (PEP 701), while pyproject declares requires-python >=3.10, so the
    generated agents were syntactically invalid on every supported version
    except the one they happened to be generated on.
    """
    key = match.group(1)[1:-1]
    return f"_st_view.get('{key}', '')"


def _transform_logic_rhs_lg(value):
    """Transform the right-hand side of an assignment for LangGraph."""
    import re
    value = re.sub(r'state\.data\.get\(', '_st_view.get(', value)
    value = re.sub(r'state\.data\[(["\'][^"\']+["\'])\]', _single_quoted, value)
    value = re.sub(r'\bstate\.data\b', 'dict(_st_view)', value)
    return value


def _generate_gate_check_lg(condition):
    """Generate a Python expression for a gate condition in LangGraph context.
    Uses state["x"] instead of state.data.get("x")."""
    import re
    c = condition.lower()

    # Handle compound conditions with 'and' / 'or'
    if ' and ' in c:
        parts = [p.strip() for p in condition.split(' and ', 1)]
        left = _generate_gate_check_lg(parts[0])
        right = _generate_gate_check_lg(parts[1])
        return f'({left}) and ({right})'
    if ' or ' in c:
        parts = [p.strip() for p in condition.split(' or ', 1)]
        left = _generate_gate_check_lg(parts[0])
        right = _generate_gate_check_lg(parts[1])
        return f'({left}) or ({right})'

    field_match = re.match(r'([\w]+(?:\.[\w]+)*)', condition)
    field_path = field_match.group(1) if field_match else None

    def accessor(path):
        parts = path.split('.')
        if len(parts) == 1:
            return f'state.get("{parts[0]}")'
        expr = 'state'
        for p in parts[:-1]:
            expr = f'{expr}.get("{p}", {{}})'
        expr = f'{expr}.get("{parts[-1]}")'
        return expr

    def num_accessor(path):
        parts = path.split('.')
        if len(parts) == 1:
            return f'state.get("{parts[0]}", 0)'
        expr = 'state'
        for p in parts[:-1]:
            expr = f'{expr}.get("{p}", {{}})'
        expr = f'{expr}.get("{parts[-1]}", 0)'
        return expr

    if '.length' in c and '> 0' in c:
        base = field_path.rsplit('.', 1)[0] if '.' in field_path else field_path
        return f'len({accessor(base)} or [])'

    if 'approaching' in c or 'capacity' in c:
        return f'(state.get("_context_token_count", 0) > state.get("_context_capacity", 100000) * 0.8)'

    if 'matches' in c or 'match' in c:
        return f'state.get("_permission_granted", True)'

    if 'is not empty' in c or 'not empty' in c:
        if field_path:
            return f'bool({accessor(field_path)})'

    if 'is empty' in c and 'not' not in c:
        if field_path:
            return f'not bool({accessor(field_path)})'

    def _is_numeric(s):
        try:
            float(s)
            return True
        except ValueError:
            return False

    def _resolve_operand(token):
        """Resolve a comparison operand — handles len(field), field.length, numeric, and plain fields."""
        len_m = re.match(r'len\((\w+)\)', token)
        if len_m:
            return f'len({accessor(len_m.group(1))} or [])'
        if '.' in token and token.split('.')[-1] == 'length':
            base = token.rsplit('.', 1)[0]
            return f'len({accessor(base)} or [])'
        if _is_numeric(token):
            return token
        return f'({num_accessor(token)})'

    # Comparison operator regex — captures len(field), field.path, or numeric on each side
    _cmp_operand = r'(len\(\w+\)|[\w.]+)'

    gte_match = re.search(_cmp_operand + r'\s*>=\s*' + _cmp_operand, condition)
    if gte_match:
        return f'{_resolve_operand(gte_match.group(1))} >= {_resolve_operand(gte_match.group(2))}'

    lte_match = re.search(_cmp_operand + r'\s*<=\s*' + _cmp_operand, condition)
    if lte_match:
        return f'{_resolve_operand(lte_match.group(1))} <= {_resolve_operand(lte_match.group(2))}'

    gt_match = re.search(_cmp_operand + r'\s*>\s*' + _cmp_operand, condition)
    if gt_match:
        return f'{_resolve_operand(gt_match.group(1))} > {_resolve_operand(gt_match.group(2))}'

    lt_match = re.search(_cmp_operand + r'\s*<\s*' + _cmp_operand, condition)
    if lt_match:
        return f'{_resolve_operand(lt_match.group(1))} < {_resolve_operand(lt_match.group(2))}'

    eq_match = re.search(r'([\w.]+)\s*==?\s*["\']?(\w+)["\']?', condition)
    if eq_match:
        lhs, rhs = eq_match.group(1), eq_match.group(2)
        if rhs.isdigit():
            return f'{num_accessor(lhs)} == {rhs}'
        if rhs in ('True', 'true'):
            return f'{accessor(lhs)} == True'
        if rhs in ('False', 'false'):
            return f'{accessor(lhs)} == False'
        if rhs in ('None', 'none', 'null'):
            return f'{accessor(lhs)} is None'
        return f'{accessor(lhs)} == "{rhs}"'

    if field_path:
        return f'bool({accessor(field_path)})'

    return 'True  # could not parse condition'


