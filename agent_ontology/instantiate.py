_LOGIC_ASSIGN_RE = re.compile(r"""state\.data\[\s*["'](\w+)["']\s*\]\s*=(?!=)""")


def _merge_reset_plan(process, input_schema, output_schema, schema_map):
    """Keys to reset to their defaults before merging an agent's reply into state.

    An agent reply is authoritative for the fields it produces. A field it
    omits must not silently keep the value an earlier call left there -- but
    only fields the reply actually *replaces*:

    - Fields also in the invoke's declared input schema are context the agent
      was handed (a verifier gets `answer` and returns `answer`). Omitting one
      means "unchanged"; resetting it erased the answer under review.
    - Fields this process's own logic assigns just before the call (e.g.
      AutoGPT's routing override of `action_type`) are that step's output.

    If the reply declares a tool decision, it also starts a new tool exchange:
    the previous decision's `tool_calls` batch and its `observation` /
    `tool_results` are stale. Without this a thought-only ReAct step recorded
    the previous action's observation, and a later single action re-ran an
    earlier `tool_calls` batch (the dispatcher reads `tool_calls` first).
    """
    out_fields = schema_map.get(output_schema, {}).get("fields", [])
    in_names = {f.get("name") for f in schema_map.get(input_schema, {}).get("fields", [])}
    logic_names = set(_LOGIC_ASSIGN_RE.findall(process.get("logic") or ""))
    plan = [
        (f.get("name"), _field_default_literal(f.get("type", "")))
        for f in out_fields
        if f.get("name") not in in_names and f.get("name") not in logic_names
    ]
    if {f.get("name") for f in out_fields} & _TOOL_DECISION_FIELDS:
        planned = {k for k, _ in plan}
        plan += [(k, d) for k, d in _TOOL_EXCHANGE_KEYS if k not in planned]
    return plan

def generate_langgraph_agent(spec, persistent_stores=False):
    """Generate a LangGraph-based Python agent script from a spec.

    Parallel to generate_agent() but outputs code using LangGraph's StateGraph
    with typed state, add_node/add_edge/add_conditional_edges.
    """
    name = spec["name"]
    entities = spec.get("entities", [])
    processes = spec.get("processes", [])
    edges = spec.get("edges", [])
    schemas = spec.get("schemas", [])
    entry_point = spec.get("entry_point")

    # Index everything
    entity_map = {e["id"]: e for e in entities}
    process_map = {p["id"]: p for p in processes}
    schema_map = {s["name"]: s for s in schemas}

    # Build adjacency
    flow_graph = {}
    for e in edges:
        if e["type"] in ("flow", "branch"):
            src = e["from"]
            flow_graph.setdefault(src, []).append((e["to"], e))

    invoke_map = {}
    for e in edges:
        if e["type"] == "invoke":
            invoke_map.setdefault(e["from"], []).append((e["to"], e))

    store_access = {}
    for e in edges:
        if e["type"] in ("read", "write"):
            store_access.setdefault(e["from"], []).append((e["to"], e["type"], e))

    # Build channel access: publish = write to channel, subscribe = read from channel
    channel_access = {}
    for e in edges:
        if e["type"] == "publish":
            channel_access.setdefault(e["from"], []).append((e["to"], "publish", e))
        elif e["type"] == "subscribe":
            channel_access.setdefault(e["to"], []).append((e["from"], "subscribe", e))

    loop_map = {}
    for e in edges:
        if e["type"] == "loop":
            loop_map[e["from"]] = (e["to"], e)

    # Entity-bridged flow map
    entity_flow = {}
    for e in edges:
        if e["type"] == "flow" and e["from"] in entity_map and e["to"] in process_map:
            entity_flow.setdefault(e["from"], []).append(e["to"])

    agents = [e for e in entities if e["type"] == "agent"]
    stores = [e for e in entities if e["type"] == "store"]
