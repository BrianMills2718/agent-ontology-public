def _runtime_tool_dispatch(tool_name, input_text):
    """Dispatch generic tool calls via shared runtime tool library."""
    if _dispatch_tool_operation is None:
        return f"[tool {tool_name} unavailable: tool_runtime import failed]"
    try:
        _result = _dispatch_tool_operation(tool_name, input_text)
    except Exception as e:
        return f"[tool {tool_name} runtime error: {type(e).__name__}: {e}]"
    if not isinstance(_result, dict):
        return str(_result)
    _handled = bool(_result.get("handled", False))
    _ok = bool(_result.get("ok", True))
    _out = str(_result.get("output", "") or "")
    if _handled and _ok:
        return _out
    if _handled and not _ok:
        _err = _result.get("error")
        return str(_err) if _err else _out
    return f"[tool {tool_name} not implemented for input: {input_text}]"

