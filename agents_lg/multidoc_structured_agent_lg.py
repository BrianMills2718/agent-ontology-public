def node_reason(state: AgentState) -> dict:
    """
    Reason
    Reason step-by-step using extracted facts to produce an answer
    """
    print(f"  → Reason")
    updates = {}

    # Invoke: reasoner
    _cur = dict(state)
    _cur.update(updates)
    reasoner_input = build_input(_cur, "ReasoningStepInput")
    reasoner_msg = json.dumps(reasoner_input, default=str)
    reasoner_raw = invoke_reasoner(reasoner_msg, output_schema="ReasoningOutput")
    reasoner_result = parse_response(reasoner_raw, "ReasoningOutput")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    reasoner_result = require_valid_output(reasoner_result, "ReasoningOutput", 'Reasoning Agent')
    updates["_schema_violations"] = len(validate_output(reasoner_result, "ReasoningOutput"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    updates["answer"] = ""
    updates["reasoning"] = ""
    updates.update(reasoner_result)
    updates["reasoning_output"] = reasoner_result
    updates["reason_result"] = reasoner_result
    print(f"    ← Reasoning Agent: {reasoner_result}")

    return updates


