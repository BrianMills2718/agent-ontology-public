def node_extract_facts(state: AgentState) -> dict:
    """
    Extract Facts
    Extract relevant facts from each source with attribution
    """
    print(f"  → Extract Facts")
    updates = {}

    # Invoke: extractor
    _cur = dict(state)
    _cur.update(updates)
    extractor_input = build_input(_cur, "ReasoningInput")
    extractor_msg = json.dumps(extractor_input, default=str)
    extractor_raw = invoke_extractor(extractor_msg, output_schema="ExtractionOutput")
    extractor_result = parse_response(extractor_raw, "ExtractionOutput")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    extractor_result = require_valid_output(extractor_result, "ExtractionOutput", 'Fact Extractor')
    updates["_schema_violations"] = len(validate_output(extractor_result, "ExtractionOutput"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    updates["extracted_facts"] = ""
    updates["contradictions"] = ""
    updates.update(extractor_result)
    updates["extraction_output"] = extractor_result
