def node_backpropagate(state: AgentState) -> dict:
    """
    Backpropagation
    Update tree statistics with the evaluation result
    """
    print(f"  → Backpropagation")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    eval_result = _st_view.get("state_evaluator_output", {})
    score = eval_result.get("score", 0.0)
    updates["is_terminal"] = eval_result.get("is_terminal", False)
    updates["iteration"] = _st_view.get("iteration", 0) + 1
    if score > _st_view.get('best_score', ''):
        updates["best_score"] = score
        updates["best_trajectory"] = _st_view.get("current_trajectory")
    print(f"Iteration {_st_view.get('iteration', '')} complete. Score: {score}")
    if updates.get("_done") or state.get("_done"):
        return updates

    # Write: Update Tree
    _store_tree_store.write(dict(state))

    return updates


