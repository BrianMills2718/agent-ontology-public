def route_check_termination(state: AgentState) -> str:
    """Gate: Search Finished? — is_terminal == True or iteration >= 30"""
    if (state.get("is_terminal") == True) or ((state.get("iteration", 0)) >= 30):
        print(f"    → continue")
        return "select_node"
    else:
        print(f"    → finish")
        return "format_output"


