def _openrouter_model_id(model):
    """Map spec model names to OpenRouter model IDs (provider/model format)."""
    if "/" in model:
        return model
    if model.startswith("gemini"):
        return f"google/{model}"
    if model.startswith("claude") or model.startswith("anthropic"):
        return f"anthropic/{model}"
    if model.startswith("gpt") or model.startswith("o1") or model.startswith("o3"):
        return f"openai/{model}"
    return model


def _normalize_temperature(model, temperature):
    """Normalize model-specific temperature constraints for llm_client/litellm."""
    try:
        model_l = str(model).lower()
    except Exception:
        model_l = ""
    if "gpt-5" in model_l:
        return 1
    return temperature


def call_llm(model, system_prompt, user_message, temperature=0.7, max_tokens=8192, retries=3, task=None, trace_id=None, max_budget=None):
    """Unified LLM call path via llm_client with observability tags."""
    global _LLM_CALL_SEQ
    if _MODEL_OVERRIDE:
        model = _MODEL_OVERRIDE
    temperature = _normalize_temperature(model, temperature)
    _LLM_CALL_SEQ += 1

    effective_task = task or _DEFAULT_TASK
    if trace_id:
        effective_trace = trace_id
    else:
        effective_trace = f"{_TRACE_PREFIX}/{_LLM_CALL_SEQ}"
    if max_budget is None:
        raw_budget = os.environ.get("AGENT_ONTOLOGY_MAX_BUDGET_USD", "0")
        try:
            effective_budget = float(raw_budget)
        except ValueError:
            effective_budget = 0.0
    else:
        effective_budget = float(max_budget)

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_message},
    ]

    kwargs = {
        "temperature": temperature,
        "max_tokens": max_tokens,
        "num_retries": retries,
    }
    if _OPENROUTER_API_KEY:
        model = _openrouter_model_id(model)
        kwargs["api_base"] = "https://openrouter.ai/api/v1"
        kwargs["api_key"] = _OPENROUTER_API_KEY

    try:
        global _LLM_CLIENT_INFO_PRINTED
        try:
            from llm_client import call_llm as llm_client_call
            import llm_client as _llm_client_pkg
        except ImportError:
            # Support monorepo layout where package lives at llm_client/llm_client
            from llm_client import call_llm as llm_client_call
            import llm_client.llm_client as _llm_client_pkg
        if not _LLM_CLIENT_INFO_PRINTED:
            _llm_path = getattr(_llm_client_pkg, "__file__", "unknown")
            _llm_version = getattr(_llm_client_pkg, "__version__", "n/a")
            print(f"    [RUNTIME] llm_client module={_llm_path} version={_llm_version}")
            _LLM_CLIENT_INFO_PRINTED = True
        result = llm_client_call(
            model,
            messages,
            task=effective_task,
            trace_id=effective_trace,
            max_budget=effective_budget,
            **kwargs,
        )
        return result.content or ""
    except Exception as e:
        # Fail loudly. Returning a stub reply here let the agent walk its graph on
        # empty fields and exit 0 with a fallback "answer", so a provider outage was
        # scored as a wrong answer. llm_client already retried (num_retries).
        print(f"    [FAIL] {type(e).__name__}: {e}")
        raise


