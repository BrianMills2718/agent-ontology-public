def build_graph():
    graph = StateGraph(AgentState)

    graph.add_node("pull_task", node_pull_task)
    graph.add_node("execute_task", node_execute_task)
    graph.add_node("enrich_and_store", node_enrich_and_store)
    graph.add_node("retrieve_context", node_retrieve_context)
    graph.add_node("create_and_reprioritize", node_create_and_reprioritize)

    graph.set_entry_point("pull_task")

    graph.add_edge("pull_task", "execute_task")
    graph.add_edge("execute_task", "enrich_and_store")
    graph.add_edge("enrich_and_store", "retrieve_context")
    graph.add_edge("retrieve_context", "create_and_reprioritize")
    graph.add_conditional_edges(
        "create_and_reprioritize",
        route_loop_create_and_reprioritize,
        {
            "pull_task": "pull_task",
            "END": END,
        }
    )

    return graph.compile()


