def node_pull_task(state: AgentState) -> dict:
    """
    Step 1: Pull task
    Dequeue the highest-priority incomplete task from the task list
    """
    print(f"  → Step 1: Pull task")
    updates = {}

    # Read: Read prior results
    vector_db_data = _store_vector_db.read()
    updates["vector_db"] = vector_db_data

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    tasks = _st_view.get("tasks", [])
    if not tasks:
        print("    No tasks remaining!")
        updates["_done"] = True
        return state
    completed = _st_view.get("completed_count", 0)
    max_tasks = _st_view.get("max_tasks", 5)
    if completed >= max_tasks:
        print(f"    Completed {completed} tasks (max {max_tasks}). Stopping.")
        updates["_done"] = True
        return state
    task = tasks.pop(0)
    updates["task"] = task
    updates["tasks"] = tasks
    updates["completed_count"] = completed + 1
    # Prepare context from vector_db stored results (top 5)
    stored_results = [e.get("text", "") for e in _st_view.get("vector_db", []) if e.get("text")]
    updates["context"] = stored_results[-5:]
    print(f"    Pulled task {completed + 1}/{max_tasks}: {task.get('description', task)}")
    print(f"    Context from prior results: {len(_st_view.get('context', ''))} items")
    if updates.get("_done") or state.get("_done"):
        return updates

    return updates


def node_execute_task(state: AgentState) -> dict:
    """
    Step 2: Execute task
    Send task, objective, and context to Execution Agent
    """
    print(f"  → Step 2: Execute task")
    updates = {}

    # Invoke: Execute task
    _cur = dict(state)
    _cur.update(updates)
    execution_agent_input = build_input(_cur, "ExecutionInput")
    execution_agent_msg = json.dumps(execution_agent_input, default=str)
    execution_agent_raw = invoke_execution_agent(execution_agent_msg, output_schema="ExecutionOutput")
    execution_agent_result = parse_response(execution_agent_raw, "ExecutionOutput")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    execution_agent_result = require_valid_output(execution_agent_result, "ExecutionOutput", 'Execution Agent')
    updates["_schema_violations"] = len(validate_output(execution_agent_result, "ExecutionOutput"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    updates["result"] = ""
    updates["task_id"] = 0
    updates.update(execution_agent_result)
    updates["execution_output"] = execution_agent_result
    updates["execute_task_result"] = execution_agent_result
    print(f"    ← Execution Agent: {execution_agent_result}")

    return updates


