def node_synthesize_review(state: AgentState) -> dict:
    """
    Synthesize Review
    Combine all three reviews into a single structured review
    """
    print(f"  → Synthesize Review")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    # Combine security, style, and logic reviews into one input for lead reviewer
    updates["synth_input"] = {
      "security_review": _st_view.get("security_review", {}),
      "style_review": _st_view.get("style_review", {}),
      "logic_review": _st_view.get("logic_review", {})
    }
    if updates.get("_done") or state.get("_done"):
        return updates

    # Flatten nested dicts
    _combined = dict(state)
    _combined.update(updates)
    for _nested_val in list(_combined.values()):
        if isinstance(_nested_val, dict):
            for _nk, _nv in _nested_val.items():
                if _nk not in _combined:
                    updates[_nk] = _nv

    # Invoke: Invoke Lead Reviewer
    _cur = dict(state)
    _cur.update(updates)
    lead_reviewer_input = build_input(_cur, "SynthesizerInput")
    lead_reviewer_msg = json.dumps(lead_reviewer_input, default=str)
    lead_reviewer_raw = invoke_lead_reviewer(lead_reviewer_msg, output_schema="SynthesizedReview")
    lead_reviewer_result = parse_response(lead_reviewer_raw, "SynthesizedReview")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    lead_reviewer_result = require_valid_output(lead_reviewer_result, "SynthesizedReview", 'Lead Reviewer')
    updates["_schema_violations"] = len(validate_output(lead_reviewer_result, "SynthesizedReview"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    updates["quality_score"] = 0
    updates["issues"] = []
    updates["recommendation"] = ""
    updates["summary"] = ""
    updates.update(lead_reviewer_result)
    updates["synthesized_review"] = lead_reviewer_result
    updates["synthesize_review_result"] = lead_reviewer_result
    print(f"    ← Lead Reviewer: {lead_reviewer_result}")

    return updates


