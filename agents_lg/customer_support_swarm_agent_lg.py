    triage_agent_raw = invoke_triage_agent(triage_agent_msg, output_schema="TriageResult")
    triage_agent_result = parse_response(triage_agent_raw, "TriageResult")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    triage_agent_result = require_valid_output(triage_agent_result, "TriageResult", 'Triage Agent')
    updates["_schema_violations"] = len(validate_output(triage_agent_result, "TriageResult"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    updates["intent"] = ""
    updates["confidence"] = ""
    updates["summary"] = ""
    updates.update(triage_agent_result)
    updates["triage_result"] = triage_agent_result
    updates["triage_result"] = triage_agent_result
    print(f"    ← Triage Agent: {triage_agent_result}")

    return updates


