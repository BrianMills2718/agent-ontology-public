def node_accept_solution(state: AgentState) -> dict:
    """
    Accept Solution
    Record the verified sub-solution and advance to the next sub-problem
    """
    print(f"  → Accept Solution")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    solution = {
        "index": _st_view.get("current_sub_index", 0),
        "description": _st_view.get("current_sub_description", ""),
        "solution_text": _st_view.get("solution_text", ""),
        "confidence": _st_view.get("confidence", 0),
    }
    solved = _st_view.get("solved_sub_solutions", [])
    solved.append(solution)
    updates["solved_sub_solutions"] = solved
    updates["current_sub_index"] = _st_view.get("current_sub_index", 0) + 1
    updates["retry_count"] = 0
    print(f"    Accepted solution for sub-problem {solution['index'] + 1}")
    if updates.get("_done") or state.get("_done"):
        return updates

    return updates


