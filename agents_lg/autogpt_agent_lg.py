def node_verify_progress(state: AgentState) -> dict:
    """
    Verify Progress
    Check latest action result against success + constraints; may request retry of current step
    """
    print(f"  → Verify Progress")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    import datetime
    constraints = _st_view.get("constraints", [])
    if not isinstance(constraints, list):
        constraints = []
    action_result = str(_st_view.get("action_result", "") or "")
    success = bool(_st_view.get("success", False))
    lc_result = action_result.lower()
    
    matched_constraints = 0
    for raw in constraints:
        text = str(raw or "").strip().lower()
        if not text:
            continue
        tokens = [tok for tok in text.split() if len(tok) >= 3]
        if not tokens:
            continue
        if all(tok in lc_result for tok in tokens[:6]):
            matched_constraints += 1
    
    constraint_count = len([c for c in constraints if str(c or "").strip()])
    constraints_ok = True
    if constraint_count > 0:
        constraints_ok = matched_constraints >= constraint_count
    verification_passed = success and constraints_ok
    
    updates["verification_checked_at"] = datetime.datetime.now().isoformat()
    updates["verification_constraint_count"] = constraint_count
    updates["verification_matched_constraints"] = matched_constraints
    updates["verification_passed"] = verification_passed
    
    if verification_passed:
        updates["verification_status"] = "pass"
        updates["verification_notes"] = "Latest action passed execution and constraint checks."
        updates["verify_retry_count"] = 0
    else:
        fail_count = int(_st_view.get("verification_fail_count", 0) or 0) + 1
        updates["verification_fail_count"] = fail_count
        retry_count = int(_st_view.get("verify_retry_count", 0) or 0)
        max_retries = int(_st_view.get("max_verify_retries", 2) or 2)
        if retry_count < max_retries:
            updates["verification_status"] = "retry"
            updates["verification_notes"] = "Verification failed; retrying current step."
            updates["verify_retry_count"] = retry_count + 1
            current_idx = int(_st_view.get("current_step_idx", 0) or 0)
            updates["current_step_idx"] = max(0, current_idx - 1)
            updates["feedback"] = f"Verification retry requested ({_st_view.get('verify_retry_count', '')}/{max_retries})."
        else:
            updates["verification_status"] = "failed_exhausted"
            updates["verification_notes"] = "Verification failed and retry budget exhausted; continuing."
            updates["feedback"] = "Verification failed but retry budget exhausted."
    if updates.get("_done") or state.get("_done"):
        return updates

    return updates


def node_synthesize(state: AgentState) -> dict:
    """
    Synthesize
    Combine all results into a final output
    """
    print(f"  → Synthesize")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    import os
    results = _st_view.get("results", [])
    print(f"    Synthesizing {len(results)} results")
    _workspace = _st_view.get("workspace_dir", "")
    _summary = results[-1] if results else "No execution results recorded."
    _files = []
    if isinstance(_workspace, str) and _workspace and os.path.isdir(_workspace):
        for _root, _dirs, _names in os.walk(_workspace):
            for _name in sorted(_names):
                _path = os.path.relpath(os.path.join(_root, _name), _workspace)
                _files.append(_path)
                if len(_files) >= 20:
                    break
            if len(_files) >= 20:
                break
    updates["artifact_files"] = _files
    updates["answer"] = (
        f"Completed {len(results)} steps for objective: {_st_view.get('objective', '')}\\n"
        f"Capability profile: {_st_view.get('capability_profile', 'restricted')}\\n"
        f"Workspace: {_workspace}\\n"
        f"Latest result:\\n{_summary}\\n"
        f"Artifacts ({len(_files)} shown):\\n" + ("\\n".join(_files) if _files else "(no files found)")
    )
    updates["_done"] = True
    if updates.get("_done") or state.get("_done"):
        return updates

    return updates


