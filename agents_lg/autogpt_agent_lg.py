def build_graph():
    graph = StateGraph(AgentState)

    graph.add_node("set_goal", node_set_goal)
    graph.add_node("resume_checkpoint", node_resume_checkpoint)
    graph.add_node("decompose", node_decompose)
    graph.add_node("think", node_think)
    graph.add_node("criticize", node_criticize)
    graph.add_node("handle_rejection", node_handle_rejection)
    graph.add_node("act", node_act)
    graph.add_node("normalize_action_routing", node_normalize_action_routing)
    graph.add_node("execute_external_call", node_execute_external_call)
    graph.add_node("execute_command", node_execute_command)
    graph.add_node("observe", node_observe)
    graph.add_node("checkpoint_state", node_checkpoint_state)
    graph.add_node("verify_progress", node_verify_progress)
    graph.add_node("synthesize", node_synthesize)

    graph.set_entry_point("set_goal")

    graph.add_edge("set_goal", "resume_checkpoint")
    graph.add_edge("resume_checkpoint", "decompose")
    graph.add_edge("decompose", "think")
    graph.add_edge("think", "criticize")
    graph.add_conditional_edges(
        "criticize",
        route_critic_gate,
        {
            "handle_rejection": "handle_rejection",
            "act": "act",
        }
    )
    graph.add_conditional_edges(
        "handle_rejection",
        route_retry_or_proceed,
        {
            "think": "think",
            "act": "act",
        }
    )
    graph.add_edge("act", "normalize_action_routing")
    graph.add_conditional_edges(
        "normalize_action_routing",
        route_execution_mode_gate,
        {
            "execute_external_call": "execute_external_call",
            "execute_command": "execute_command",
        }
    )
    graph.add_edge("execute_external_call", "observe")
    graph.add_edge("execute_command", "observe")
    graph.add_edge("observe", "checkpoint_state")
    graph.add_edge("checkpoint_state", "verify_progress")
    graph.add_conditional_edges(
        "verify_progress",
        route_check_done,
        {
            "think": "think",
            "synthesize": "synthesize",
        }
    )
    graph.add_edge("synthesize", END)

    return graph.compile()


