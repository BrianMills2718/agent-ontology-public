    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    depth = _st_view.get("depth", 0)
    print(f"    Decomposing at depth {depth}...")
    if updates.get("_done") or state.get("_done"):
        return updates

    # Flatten nested dicts
    _combined = dict(state)
    _combined.update(updates)
