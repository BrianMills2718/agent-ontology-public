def node_receive_problem(state: AgentState) -> dict:
    """
    Receive Problem
    Accept the problem input and initialize the tree-of-thought state
    """
    print(f"  → Receive Problem")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    updates["current_depth"] = 0
    updates["max_depth"] = _st_view.get("max_depth", 3)
    updates["k_candidates"] = _st_view.get("k_candidates", 3)
    updates["top_n"] = _st_view.get("top_n", 2)
    updates["all_thoughts"] = []
    # Initialize with root node representing the problem itself
    root = {
        "thought_id": "root",
        "content": _st_view.get("problem", ""),
        "depth": 0,
        "score": 0,
        "parent_id": None
    }
    updates["current_parents"] = [root]
    _list = list(_st_view.get("all_thoughts", []) or []); _list.append(root); updates["all_thoughts"] = _list
    print(f"    Problem: {_st_view.get('problem', '')[:100]}")
    print(f"    Config: depth={_st_view.get('max_depth', '')}, K={_st_view.get('k_candidates', '')}, top-N={_st_view.get('top_n', '')}")
    if updates.get("_done") or state.get("_done"):
        return updates

    return updates


def node_generate_thoughts(state: AgentState) -> dict:
    """
    Generate Thoughts
    For each current parent thought, invoke the generator to produce K candidate children
    """
    print(f"  → Generate Thoughts")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    updates["current_depth"] = _st_view.get("current_depth", 0) + 1
    parents = _st_view.get("current_parents", [])
    updates["parent_index"] = 0
    updates["generated_children"] = []
    print(f"    Generating thoughts at depth {_st_view.get('current_depth', '')} for {len(parents)} parent(s)")
    if updates.get("_done") or state.get("_done"):
        return updates

    # Flatten nested dicts
    _combined = dict(state)
    _combined.update(updates)
    for _nested_val in list(_combined.values()):
        if isinstance(_nested_val, dict):
            for _nk, _nv in _nested_val.items():
                if _nk not in _combined:
                    updates[_nk] = _nv

    # Invoke: Generate K candidate thoughts
    _cur = dict(state)
    _cur.update(updates)
    thought_generator_input = build_input(_cur, "GeneratorInput")
    thought_generator_msg = json.dumps(thought_generator_input, default=str)
    thought_generator_raw = invoke_thought_generator(thought_generator_msg, output_schema="GeneratedThoughts")
    thought_generator_result = parse_response(thought_generator_raw, "GeneratedThoughts")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    thought_generator_result = require_valid_output(thought_generator_result, "GeneratedThoughts", 'Thought Generator')
    updates["_schema_violations"] = len(validate_output(thought_generator_result, "GeneratedThoughts"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    updates["thoughts"] = []
    updates.update(thought_generator_result)
    updates["generated_thoughts"] = thought_generator_result
    updates["generate_thoughts_result"] = thought_generator_result
    print(f"    ← Thought Generator: {thought_generator_result}")

    return updates


