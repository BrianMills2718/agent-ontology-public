def node_think_or_act(state: AgentState) -> dict:
    """
    Think / Act
    Send trajectory to reasoning agent, get next Thought, Action, or Answer
    """
    print(f"  → Think / Act")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    updates["step_count"] = _st_view.get("step_count", 0) + 1
    print(f"    Step {_st_view.get('step_count', '')}/{_st_view.get('max_steps', 10)}")
    if updates.get("_done") or state.get("_done"):
        return updates

    # Flatten nested dicts
    _combined = dict(state)
    _combined.update(updates)
    for _nested_val in list(_combined.values()):
        if isinstance(_nested_val, dict):
            for _nk, _nv in _nested_val.items():
                if _nk not in _combined:
                    updates[_nk] = _nv

    # Invoke: Get next step
    _cur = dict(state)
    _cur.update(updates)
    reasoning_agent_input = build_input(_cur, "ReActInput")
    reasoning_agent_msg = json.dumps(reasoning_agent_input, default=str)
    reasoning_agent_raw = invoke_reasoning_agent(reasoning_agent_msg, output_schema="ReActStep")
    reasoning_agent_result = parse_response(reasoning_agent_raw, "ReActStep")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    reasoning_agent_result = require_valid_output(reasoning_agent_result, "ReActStep", 'Reasoning Agent')
    updates["_schema_violations"] = len(validate_output(reasoning_agent_result, "ReActStep"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    updates["type"] = ""
    updates["thought"] = ""
    updates["action"] = ""
    updates["tool_name"] = ""
    updates["tool_input"] = ""
    updates["answer"] = ""
    updates["tool_calls"] = []
    updates["observation"] = ""
    updates["tool_results"] = []
    updates.update(reasoning_agent_result)
    updates["re_act_step"] = reasoning_agent_result
    updates["think_or_act_result"] = reasoning_agent_result
    print(f"    ← Reasoning Agent: {reasoning_agent_result}")

    return updates


def node_execute_action(state: AgentState) -> dict:
    """
    Execute Action
    Run the tool specified in the action and capture observation
    """
    print(f"  → Execute Action")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    action = _st_view.get("action", "")
    tool_name = _st_view.get("tool_name", "search")
    tool_input = _st_view.get("tool_input", action)
    print(f"    Action[{tool_name}]: {tool_input[:100]}")
    if updates.get("_done") or state.get("_done"):
        return updates

    # Flatten nested dicts
    _combined = dict(state)
    _combined.update(updates)
    for _nested_val in list(_combined.values()):
        if isinstance(_nested_val, dict):
            for _nk, _nv in _nested_val.items():
                if _nk not in _combined:
                    updates[_nk] = _nv

    # Tool dispatch (single call or tool_calls batch)
    _cur = dict(state)
    _cur.update(updates)
    _batch_results = []
    _calls = _cur.get("tool_calls")
    if isinstance(_calls, list) and _calls:
        _dispatch_items = _calls
    else:
        _dispatch_items = [{
            "tool_name": _cur.get("tool_name", ""),
            "arguments": _cur.get("tool_input", _cur.get("action", "")),
        }]
    for _call in _dispatch_items:
        if not isinstance(_call, dict):
            _call = {"tool_name": "", "arguments": _call}
        _tool_name = str(_call.get("tool_name") or _call.get("name") or _call.get("tool") or _call.get("recipient_name") or "").lower().strip()
        if _tool_name.startswith("functions."):
            _tool_name = _tool_name.split(".", 1)[1]
        _tool_input = _call.get("arguments", _call.get("args", _call.get("parameters", _call.get("input", ""))))
        if isinstance(_tool_input, (dict, list)):
            _tool_input = json.dumps(_tool_input, ensure_ascii=False)
        else:
            _tool_input = str(_tool_input)
        if _tool_name in {'kb search', 'kb_search', 'search_tool', 'search_tool_tool', 'tool_search_tool'}:
            _tool_result = tool_search_tool(_tool_input)
            _tool_impl = "search_tool"
        elif _tool_name in {'kb lookup', 'kb_lookup', 'lookup_tool', 'lookup_tool_tool', 'tool_lookup_tool'}:
            _tool_result = tool_lookup_tool(_tool_input)
            _tool_impl = "lookup_tool"
        elif _tool_name in {'calculate', 'calculate_tool', 'calculate_tool_tool', 'tool_calculate_tool'}:
            _tool_result = tool_calculate_tool(_tool_input)
            _tool_impl = "calculate_tool"
        else:
            _tool_result = _runtime_tool_dispatch(_tool_name, _tool_input)
            if isinstance(_tool_result, str) and _tool_result.startswith("[tool ") and "not implemented" in _tool_result:
                _tool_result = f"Unknown tool: {_tool_name}. Available: kb search, kb lookup, calculate"
                _tool_impl = "unknown"
            else:
                _tool_impl = "runtime_dispatch"
        _batch_results.append({"tool_name": _tool_name or _tool_impl, "output": _tool_result})
    if len(_batch_results) == 1:
        _tool_result = _batch_results[0]["output"]
    else:
        _tool_result = json.dumps(_batch_results, ensure_ascii=False, indent=2)
    updates["tool_results"] = _batch_results
    updates["observation"] = _tool_result
    print(f"    Observation: {_tool_result[:200]}")

    return updates


def node_record_step(state: AgentState) -> dict:
    """
    Record Step
    Append the current step (thought/action/observation) to trajectory
    """
    print(f"  → Record Step")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    # The prompt asks for tool_name/tool_input on an action, not the free-text
    # `action` field; record what actually ran so the next step can see it.
    _action = _st_view.get("action", "")
    if not _action and _st_view.get("tool_name"):
        _action = f"{_st_view.get('tool_name')}[{_st_view.get('tool_input', '')}]"
    elif not _action and _st_view.get("tool_calls"):
        _action = json.dumps(_st_view.get("tool_calls"), default=str)
    step = {
        "step_num": _st_view.get("step_count", 0),
        "thought": _st_view.get("thought", ""),
        "action": _action,
        "observation": _st_view.get("observation", ""),
    }
    trajectory = _st_view.get("trajectory", [])
    trajectory.append(step)
    updates["trajectory"] = trajectory
    print(f"    Trajectory length: {len(trajectory)}")
    if updates.get("_done") or state.get("_done"):
        return updates

    # Write: Persist step
    _cur = dict(state)
    _cur.update(updates)
    # Persist the record this step keeps, not a rebuild from state.
    trajectory_store_write = {_k: step[_k] for _k in ['step_num', 'thought', 'action', 'observation']}
    _store_trajectory_store.write(trajectory_store_write)

    return updates


