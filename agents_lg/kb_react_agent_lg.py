def tool_search_tool(input_text):
    """KB Search: Search the knowledge base by name or keyword to find entity IDs"""
    _ext = _external_tool_dispatch("semantic_search", {"query": str(input_text), "tool_id": "search_tool"})
    if _ext.get("handled"):
        if not _ext.get("ok", True):
            return f"Search error: {_ext.get('error', 'external adapter failure')}"
        _text = _ext.get("text", "")
        if _text:
            return _text
        _data = _ext.get("data")
        if _data is not None:
            try:
                return json.dumps(_data, ensure_ascii=False)
            except Exception:
                return str(_data)

    import requests
    import re as _re
    _headers = {"User-Agent": "AgentOntology/1.0 (agent research project)"} 
    try:
        resp = requests.get("https://en.wikipedia.org/w/api.php", params={
            "action": "query", "list": "search", "srsearch": input_text,
            "format": "json", "srlimit": 5
        }, headers=_headers, timeout=10)
        data = resp.json()
        results = data.get("query", {}).get("search", [])
        if not results:
            return f"No results found for: {input_text}"
        lines = []
        for r in results:
            snippet = _re.sub(r"<[^>]+>", "", r.get("snippet", ""))
            lines.append(f"{r['title']}: {snippet}")
        return "\n".join(lines)
    except Exception as e:
        return f"Search error: {e}"


def tool_lookup_tool(input_text):
    """KB Lookup: Look up full details of a knowledge base entity by its ID"""
    _ext = _external_tool_dispatch("lookup", {"query": str(input_text), "tool_id": "lookup_tool"})
    if _ext.get("handled"):
        if not _ext.get("ok", True):
            return f"Lookup error: {_ext.get('error', 'external adapter failure')}"
        _text = _ext.get("text", "")
        if _text:
            return _text
        _data = _ext.get("data")
        if _data is not None:
            try:
                return json.dumps(_data, ensure_ascii=False)
            except Exception:
                return str(_data)

    import requests
    _headers = {"User-Agent": "AgentOntology/1.0 (agent research project)"}
    try:
        resp = requests.get("https://en.wikipedia.org/w/api.php", params={
            "action": "query", "titles": input_text, "prop": "extracts",
            "exintro": True, "explaintext": True, "format": "json"
        }, headers=_headers, timeout=10)
        data = resp.json()
        pages = data.get("query", {}).get("pages", {})
        for pid, page in pages.items():
            if pid == "-1":
                return f"No Wikipedia article found for: {input_text}"
            extract = page.get("extract", "")
            if extract:
                return extract[:1500]
            return f"Article found but no extract available for: {input_text}"
        return f"No results for: {input_text}"
    except Exception as e:
        return f"Lookup error: {e}"


def tool_calculate_tool(input_text):
    """Calculate: Evaluate a mathematical expression"""
    import math
    _safe_ns = {
        "abs": abs, "round": round, "min": min, "max": max,
        "sum": sum, "pow": pow, "int": int, "float": float,
        "math": math, "pi": math.pi, "e": math.e,
        "sqrt": math.sqrt, "log": math.log, "sin": math.sin,
        "cos": math.cos, "tan": math.tan,
    }
    try:
        result = eval(input_text, {"__builtins__": {}}, _safe_ns)
        return str(result)
    except Exception as e:
        return f"Calculation error: {e}"



