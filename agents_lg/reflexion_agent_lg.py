def node_store_reflection(state: AgentState) -> dict:
    """
    Store Reflection
    Append the reflection to episodic memory and prepare for retry
    """
    print(f"  → Store Reflection")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    reflection = _st_view.get("reflection", "")
    strategy = _st_view.get("suggested_strategy", "")
    trial = _st_view.get("trial", 0)
    # Accumulate reflections
    reflections = _st_view.get("reflections", [])
    reflections.append(reflection)
    updates["reflections"] = reflections
    # Build episode entry
    episode = {
        "trial_number": trial,
        "answer": _st_view.get("answer", ""),
        "score": _st_view.get("score", 0.0),
        "failure_reason": _st_view.get("failure_reason", ""),
        "reflection": reflection,
        "suggested_strategy": strategy,
    }
    episodes = _st_view.get("episodes", [])
    episodes.append(episode)
    updates["episodes"] = episodes
    print(f"    Stored reflection #{len(reflections)}: {reflection[:80]}")
    if updates.get("_done") or state.get("_done"):
        return updates

    # Write: Persist episode
    _cur = dict(state)
    _cur.update(updates)
    # Persist the record this step keeps, not a rebuild from state.
    episodic_memory_write = {_k: episode[_k] for _k in ['trial_number', 'answer', 'score', 'failure_reason', 'reflection', 'suggested_strategy']}
    _store_episodic_memory.write(episodic_memory_write)

    return updates


