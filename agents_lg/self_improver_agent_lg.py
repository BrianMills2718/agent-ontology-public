class _StateCompat:
    """Wrapper to make LangGraph state compatible with test harness."""
    def __init__(self, state_dict):
        self.data = {k: v for k, v in state_dict.items() if not k.startswith("_")}
        self.data.update({k: v for k, v in state_dict.items() if k.startswith("_")})
        self.iteration = state_dict.get("_iteration", 0)
        self.schema_violations = state_dict.get("_schema_violations", 0)

    def get(self, key, default=None):
        return self.data.get(key, default)


MAX_ITERATIONS = int(os.environ.get("AGENT_ONTOLOGY_MAX_ITER", "100"))


def run(initial_data=None):
    """Self Improver — LangGraph execution"""
    app = build_graph()

    # Build initial state
    state = {}
    if initial_data:
        state.update(initial_data)
    state["_iteration"] = 0
    state["_schema_violations"] = 0
    state["_done"] = False

    print(f"\n════════════════════════════════════════════════════════════")
    print(f"  Self Improver (LangGraph)")
    print(f"  Reads an agent spec YAML, analyzes it for structural weaknesses (lint warnings, missing patterns, complexity issues), proposes mutations, validates the result, and outputs an improved spec.")
    print(f"════════════════════════════════════════════════════════════\n")

    # LangGraph recursion limit maps roughly to our MAX_ITERATIONS. Same contract
    # as the custom backend: hitting the limit returns the partial state with
    # clean_exit=False; any other exception propagates to the caller (so the
    # benchmark records ERROR and `python <agent>` exits non-zero).
    from langgraph.errors import GraphRecursionError
    final_state = dict(state)
    _clean_exit = True
    try:
        for _snapshot in app.stream(state, {"recursion_limit": MAX_ITERATIONS * 3}, stream_mode="values"):
            final_state = _snapshot
    except GraphRecursionError as e:
        print(f"\n  [STOPPED] {type(e).__name__}: {e}")
        final_state = dict(final_state)
        final_state["_error"] = f"{type(e).__name__}: {e}"
        _clean_exit = False
    except Exception:
        dump_trace(iterations=final_state.get("_iteration", 0), clean_exit=False)
        raise

    dump_trace(iterations=final_state.get("_iteration", 0), clean_exit=_clean_exit)
    print(f"\nFinal state keys: {list(final_state.keys())}")
    return _StateCompat(final_state)


if __name__ == "__main__":
    run()