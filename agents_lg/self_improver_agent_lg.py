def node_analyze_spec(state: AgentState) -> dict:
    """
    Analyze Spec
    Run lint, verify, and pattern detection on the current spec
    """
    print(f"  → Analyze Spec")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    import yaml as _yaml
    import tempfile, os
    spec_yaml = _st_view.get("current_spec_yaml", "")
    # Write spec to temp file for analysis tools
    tmp = tempfile.NamedTemporaryFile(mode='w', suffix='.yaml', delete=False)
    tmp.write(spec_yaml)
    tmp.close()
    tmp_path = tmp.name
    try:
        # Parse the spec
        spec = _yaml.safe_load(spec_yaml)
        updates["spec_name"] = spec.get("name", "unknown")
        # Run lint
        try:
            from agent_ontology.lint import lint_spec
            lint_results = lint_spec(spec)
            updates["lint_warnings"] = [{"rule": r.code, "severity": r.severity, "message": r.message} for r in lint_results]
            print(f"    Lint: {len(lint_results)} warnings")
        except Exception as e:
            updates["lint_warnings"] = []
            print(f"    Lint failed: {e}")
        # Run verify
        try:
            from agent_ontology.verify import verify_spec
            passes, failures = verify_spec(spec, spec_path=tmp_path)
            updates["verify_issues"] = [{"check": f, "status": "fail"} for f in failures]
            print(f"    Verify: {len(failures)} issues, {len(passes)} passed")
        except Exception as e:
            updates["verify_issues"] = []
            print(f"    Verify failed: {e}")
        # Detect patterns
        try:
            from agent_ontology.patterns import detect_patterns
            patterns = detect_patterns(spec)
            updates["detected_patterns"] = list(patterns.keys()) if isinstance(patterns, dict) else patterns
            print(f"    Patterns: {_st_view.get('detected_patterns', '')}")
        except Exception as e:
            updates["detected_patterns"] = []
            print(f"    Pattern detection failed: {e}")
        # Count entities/processes/edges
        updates["entity_count"] = len(spec.get("entities", []))
        updates["process_count"] = len(spec.get("processes", []))
        updates["edge_count"] = len(spec.get("edges", []))
        updates["schema_count"] = len(spec.get("schemas", []))
    finally:
        os.unlink(tmp_path)
    if updates.get("_done") or state.get("_done"):
        return updates

    return updates


