def tool_filesystem_tool(input_text):
    """filesystem MCP: """
    """Dispatch to MCP server tools."""
    import subprocess
    import json as _json

    # Parse input: expect JSON with {server, tool, args} or plain text
    try:
        req = _json.loads(input_text) if input_text.strip().startswith("{") else {"tool": input_text}
    except _json.JSONDecodeError:
        req = {"tool": input_text}

    server = req.get("server", "default")
    tool_name = req.get("tool", "")
    tool_args = req.get("args", {})

    _ext = _external_tool_dispatch("mcp_tool_call", {"server": server, "tool": tool_name, "args": tool_args, "tool_id": "filesystem_tool"})
    if _ext.get("handled"):
        if not _ext.get("ok", True):
            return f"MCP error: {_ext.get('error', 'external adapter failure')}"
        _text = _ext.get("text", "")
        if _text:
            return _text
        _data = _ext.get("data")
        if _data is not None:
            try:
                return _json.dumps(_data, ensure_ascii=False, indent=2)
            except Exception:
                return str(_data)

    # MCP JSON-RPC call via stdio transport
    rpc_request = _json.dumps({
        "jsonrpc": "2.0",
        "id": 1,
        "method": "tools/call",
        "params": {"name": tool_name, "arguments": tool_args}
    })

    mcp_cmd = os.environ.get(f"MCP_SERVER_{server.upper()}", f"npx -y @modelcontextprotocol/server-{server}")
    try:
        result = subprocess.run(
            mcp_cmd.split(),
            input=rpc_request,
            capture_output=True, text=True, timeout=30
        )
        if result.returncode == 0 and result.stdout.strip():
            resp = _json.loads(result.stdout)
            return _json.dumps(resp.get("result", resp), indent=2)
        return f"MCP call to {server}/{tool_name} returned: {result.stderr or result.stdout}"
    except FileNotFoundError:
        return f"MCP server '{server}' not found. Set MCP_SERVER_{server.upper()} env var or install the server."
    except subprocess.TimeoutExpired:
        return f"MCP call to {server}/{tool_name} timed out (30s)"
    except Exception as e:
        return f"MCP error: {e}"


def tool_web_tool(input_text):
    """web search/fetch: """
    _ext = _external_tool_dispatch("semantic_search", {"query": str(input_text), "tool_id": "web_tool"})
    if _ext.get("handled"):
        if not _ext.get("ok", True):
            return f"Search error: {_ext.get('error', 'external adapter failure')}"
        _text = _ext.get("text", "")
        if _text:
            return _text
        _data = _ext.get("data")
        if _data is not None:
            try:
                return json.dumps(_data, ensure_ascii=False)
            except Exception:
                return str(_data)

    import requests
    import re as _re
    _headers = {"User-Agent": "AgentOntology/1.0 (agent research project)"} 
    try:
        resp = requests.get("https://en.wikipedia.org/w/api.php", params={
            "action": "query", "list": "search", "srsearch": input_text,
            "format": "json", "srlimit": 5
        }, headers=_headers, timeout=10)
        data = resp.json()
        results = data.get("query", {}).get("search", [])
        if not results:
            return f"No results found for: {input_text}"
        lines = []
        for r in results:
            snippet = _re.sub(r"<[^>]+>", "", r.get("snippet", ""))
            lines.append(f"{r['title']}: {snippet}")
        return "\n".join(lines)
    except Exception as e:
        return f"Search error: {e}"


