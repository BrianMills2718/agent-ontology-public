# Graph Construction
# ═══════════════════════════════════════════════════════════

def build_graph():
    graph = StateGraph(AgentState)

    graph.add_node("receive_request", node_receive_request)
    graph.add_node("load_context", node_load_context)
    graph.add_node("enforce_policy", node_enforce_policy)
    graph.add_node("initialize_plan", node_initialize_plan)
    graph.add_node("publish_progress", node_publish_progress)
    graph.add_node("emit_progress", node_emit_progress)
    graph.add_node("decide_next_action", node_decide_next_action)
    graph.add_node("run_tools", node_run_tools)
    graph.add_node("observe_results", node_observe_results)
    graph.add_node("update_plan_state", node_update_plan_state)
    graph.add_node("finalize_response", node_finalize_response)
    graph.add_node("emit_final", node_emit_final)
    graph.add_node("persist_turn", node_persist_turn)

    graph.set_entry_point("receive_request")

    graph.add_edge("receive_request", "load_context")
    graph.add_edge("load_context", "enforce_policy")
    graph.add_conditional_edges(
        "enforce_policy",
        route_planning_gate,
        {
            "initialize_plan": "initialize_plan",
            "decide_next_action": "decide_next_action",
        }
    )
    graph.add_edge("initialize_plan", "publish_progress")
    graph.add_edge("publish_progress", "decide_next_action")
    graph.add_edge("publish_progress", "emit_progress")
    graph.add_edge("emit_progress", END)
    graph.add_conditional_edges(
        "decide_next_action",
        route_action_gate,
        {
            "run_tools": "run_tools",
            "finalize_response": "finalize_response",
        }
    )
    graph.add_edge("run_tools", "observe_results")
    graph.add_edge("observe_results", "update_plan_state")
    graph.add_conditional_edges(
        "update_plan_state",
        route_completion_gate,
        {
            "publish_progress": "publish_progress",
            "finalize_response": "finalize_response",
        }
    )
    graph.add_edge("finalize_response", "emit_final")
    graph.add_edge("emit_final", "persist_turn")
    graph.add_conditional_edges(
        "persist_turn",
        route_loop_persist_turn,
        {
            "receive_request": "receive_request",
            "END": END,
        }
    )

    return graph.compile()


