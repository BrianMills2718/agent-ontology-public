def node_receive_problem(state: AgentState) -> dict:
    """
    Receive Problem
    """
    print(f"  → Receive Problem")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    updates["goal"] = _st_view.get("problem", _st_view.get("query", ""))
    updates["current_state"] = "Initial state: " + _st_view.get('goal', '')
    updates["best_path"] = []
    updates["best_reward"] = 0
    updates["iteration"] = 0
    updates["max_iterations"] = _st_view.get("max_iterations", 5)
    if updates.get("_done") or state.get("_done"):
        return updates

    return updates


