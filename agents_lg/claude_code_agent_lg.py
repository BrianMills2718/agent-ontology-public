def node_llm_call(state: AgentState) -> dict:
    """
    LLM CALL
    Send full context to Claude API. This is the inner loop target — returns here after every tool execution.
    """
    print(f"  → LLM CALL")
    updates = {}

    # Invoke: API call
    _cur = dict(state)
    _cur.update(updates)
    claude_input = build_input(_cur, "ApiPayload")
    claude_msg = json.dumps(claude_input, default=str)
    claude_raw = invoke_claude(claude_msg, output_schema="ApiResponse")
    claude_result = parse_response(claude_raw, "ApiResponse")
    # Refuse a reply whose fields violate their declared types: nothing merged or routed.
    claude_result = require_valid_output(claude_result, "ApiResponse", 'Claude (LLM)')
    updates["_schema_violations"] = len(validate_output(claude_result, "ApiResponse"))
    # Reset what this reply replaces before merging it: parse_response returns only
    # the keys the LLM included, so an omitted output (e.g. tool_name on a thought-only
    # step) must not keep a prior call's value. Declared inputs and this step's own
    # logic outputs are left alone -- omitting them means unchanged, not empty.
    updates["content"] = []
    updates["stop_reason"] = ""
    updates["usage"] = ""
    updates.update(claude_result)
    updates["api_response"] = claude_result
    updates["llm_call_result"] = claude_result
    print(f"    ← Claude (LLM): {claude_result}")

    return updates


def node_parse_response(state: AgentState) -> dict:
    """
    PARSE RESPONSE
    Extract text blocks and tool_use blocks from API response
    """
    print(f"  → PARSE RESPONSE")
    updates = {}

    # Logic from spec. Reads go through _st_view so a line sees what an
    # earlier line of this node wrote, as in the custom backend.
    _st_view = ChainMap(updates, state)
    _resp = _st_view.get("api_response", {})
    _content = _resp.get("content") if isinstance(_resp, dict) else None
    if not isinstance(_content, list):
      _content = []
    _text_blocks = []
    _tool_calls = []
    for _b in _content:
      if not isinstance(_b, dict):
        continue
      _bt = _b.get("type")
      if _b.get("text"):
        _text_blocks.append(str(_b.get("text")))
      elif _bt == "tool_use":
        _tool_calls.append({
          "id": _b.get("id", "tool_call"),
          "tool_name": _b.get("tool_name", ""),
          "input": _b.get("tool_input", {}),
        })
    
    # If model returned no content blocks, keep a debuggable fallback.
    if not _text_blocks:
      if isinstance(_resp, dict) and _resp.get("error"):
        _text_blocks = [str(_resp.get("error"))]
      elif isinstance(_resp, dict):
        _text_blocks = [json.dumps(_resp, default=str)]
      else:
        _text_blocks = [str(_resp)]
    
    updates["parsed_response"] = {"text_blocks": _text_blocks, "tool_calls": _tool_calls}
    if updates.get("_done") or state.get("_done"):
        return updates

    return updates


